class _FileWriter {
  final IrFile file;
  final String area;
  final String package;
  final String module;
  final _Symbols symbols;
  final Set<String> imports = {};

  _FileWriter({
    required this.file,
    required this.area,
    required this.package,
    required this.module,
    required this.symbols,
  });

  late final IrIndex _index = irFileIndex(area, file);

  _Types _types([Set<String> typeParameters = const {}]) =>
      _Types(symbols, package, module, typeParameters, imports);

  String render() {
    final body = <String>[];
    for (final e in _index.topLevel) {
      body
        ..add('')
        ..addAll(_declaration(e));
    }
    final banner = [
      '// $_generated',
      for (final c in file.file.comments)
        if (c.isBanner && !c.text.contains('GENERATED')) c.text,
    ];
    return '${[...banner, '', 'package $package', ..._imports(), ...body].join('\n')}\n';
  }

  List<String> _imports() => _importBlock(imports, module);

  List<String> _declaration(IrEntry e) {
    final d = e.declaration;
    final members = _index.membersOf(e);
    final where = '${file.file.path}: ${d.name}';
    final typeParameters = irTypeParameterNames(d.typeParameters, where);
    final types = _types(typeParameters);
    final head = _doc(d, indent: '');
    switch (_declarationShape(_index, e)) {
      case IrShape.catalogue:
        final entries = d.kind == CsDeclarationKind.enumType
            ? [
                for (final m in members)
                  if (m.kind == CsDeclarationKind.field) (m, m.name),
              ]
            : [for (final m in members) (m, irInitialiserString(m)!)];
        return [
          ...head,
          'type ${d.name} string',
          '',
          '// The values of [${d.name}].',
          'const (',
          for (final (i, (m, v)) in entries.indexed) ...[
            if (i > 0) '',
            ..._doc(m, indent: '\t'),
            '\t${d.name}${_exported(m.name)} ${d.name} = ${jsonEncode(v)}',
          ],
          ')',
        ];
      case IrShape.plainData:
        return [
          ...head,
          'type ${d.name}${_goTypeParameters(typeParameters)} struct {',
          ..._fields(d.name, members, types, entity: false),
          '}',
        ];
      case IrShape.entity:
        final table =
            irString(irMarker(d, 'CsTable')?.positional.firstOrNull) ??
            irSnake(d.name);
        return [
          ...head,
          'type ${d.name} struct {',
          ..._fields(d.name, members, types, entity: true),
          '}',
          '',
          '// ${d.name}Table is the table [${d.name}] is stored in.',
          'const ${d.name}Table = ${jsonEncode(table)}',
        ];
      case IrShape.contract:
        final embedded = d.superclass == null
            ? const <String>[]
            : ['\t${types.of(d.superclass!)}'];
        final methods = [
          for (final m in members)
            if (m.kind == CsDeclarationKind.method)
              for (final b in m.bodies)
                if (b.name == m.name) ...[
                  ..._doc(m, indent: '\t'),
                  '\t${_signature(m.name, b, types)}',
                ],
        ];
        return [
          ...head,
          'type ${d.name}${_goTypeParameters(typeParameters)} interface {',
          ...embedded,
          if (embedded.isNotEmpty && methods.isNotEmpty) '',
          ...methods,
          '}',
        ];
      case IrShape.serviceUnit:
        return _serviceUnit(d, members, head, types);
      case IrShape.classType:
        return _classType(e, members, head, types, typeParameters);
      case IrShape.layout:
        throw StateError('refused by _declarationShape');
      case IrShape.variable:
        if (file.file.constructions.any((c) => c.holder == d.name)) {
          throw IrMapException(
            '$where: a construction has no Go form in the server mapper',
          );
        }
        final value = irInitialiserString(d);
        if (value == null) {
          throw IrMapException(
            '$where: the initialiser `${d.initialiser}` has no Go form',
          );
        }
        return [...head, 'const ${d.name} = ${jsonEncode(value)}'];
    }
  }

  /// Refuses an instance field Go has no place for: a struct field has no
  /// initialiser.
  void _plainField(String owner, CsDeclaration m) {
    if (m.isStatic) {
      throw IrMapException(
        '${file.file.path}: the static field $owner.${m.name} has no Go rule '
        'in a struct',
      );
    }
    if (m.hasInitialiser ||
        file.file.constructions.any((c) => c.holder == '$owner.${m.name}')) {
      throw IrMapException(
        '${file.file.path}: the initialiser of $owner.${m.name} has no Go '
        'rule in a struct',
      );
    }
  }

  /// A struct's fields, a blank line between each so no two align.
  List<String> _fields(
    String owner,
    List<CsDeclaration> members,
    _Types types, {
    required bool entity,
  }) {
    final out = <String>[];
    for (final m in members) {
      if (m.kind != CsDeclarationKind.field) continue;
      _plainField(owner, m);
      final dart = m.declaredType ?? 'Object';
      final nullable = dart.trim().endsWith('?');
      final json = '${m.name}${nullable ? ',omitempty' : ''}';
      final String tag;
      if (entity) {
        final col = irMarker(m, 'CsColumn');
        final column = irString(col?.named['column']) ?? irSnake(m.name);
        tag = '`db:"$column" json:"$json"`';
      } else {
        tag = '`json:"$json"`';
      }
      if (out.isNotEmpty) out.add('');
      out
        ..addAll(_doc(m, indent: '\t'))
        ..add('\t${_exported(m.name)} ${types.of(dart)} $tag');
    }
    return out;
  }

  String _parameters(CsMethodBody b, _Types types) => [
    'ctx context.Context',
    for (final p in b.parameters)
      '${_local(p.name)} ${types.of(p.type ?? 'Object')}',
  ].join(', ');

  String _signature(String name, CsMethodBody b, _Types types) {
    imports.add('context');
    return '${_exported(name)}(${_parameters(b, types)}) '
        '${_results(types.resultOf(b.returnType))}';
  }

  List<String> _serviceUnit(
    CsDeclaration d,
    List<CsDeclaration> members,
    List<String> head,
    _Types types,
  ) {
    final handlers = [
      for (final m in members)
        if (m.kind == CsDeclarationKind.method)
          if (m.bodies.where((b) => b.name == m.name).firstOrNull case final b?)
            (m, b),
    ];
    if (members.any((m) => m.kind == CsDeclarationKind.field)) {
      throw IrMapException(
        '${file.file.path}: the service unit ${d.name} has fields, which the '
        'Go mapper has no rule for',
      );
    }
    final stub = 'Unimplemented${d.name}';
    return [
      ...head,
      if (handlers.isEmpty)
        'type ${d.name} interface{}'
      else ...[
        'type ${d.name} interface {',
        for (final (i, (m, b)) in handlers.indexed) ...[
          if (i > 0) '',
          ..._doc(m, indent: '\t'),
          '\t${_signature(m.name, b, types)}',
        ],
        '}',
      ],
      '',
      '// $stub implements [${d.name}], every handler returning',
      '// [tom.ErrNotImplemented] until Phase 6 writes it.',
      'type $stub struct{}',
      '',
      'var _ ${d.name} = $stub{}',
      for (final (m, b) in handlers) ...[
        '',
        '// ${_exported(m.name)} returns [tom.ErrNotImplemented].',
        'func ($stub) ${_signature(m.name, b, types)} {',
        _notImplemented(b, m, types),
        '}',
      ],
    ];
  }

  String _notImplemented(CsMethodBody b, CsDeclaration m, _Types types) {
    imports.add('$module/$_tom');
    final message = jsonEncode(b.thrownMessage ?? b.thrownLiteral ?? m.name);
    final value = types.resultOf(b.returnType);
    return value == null
        ? '\treturn tom.NotImplemented($message)'
        : '\tvar zero $value\n\treturn zero, tom.NotImplemented($message)';
  }

  List<String> _classType(
    IrEntry e,
    List<CsDeclaration> members,
    List<String> head,
    _Types types,
    Set<String> typeParameters,
  ) {
    final d = e.declaration;
    final fields = [
      for (final m in members)
        if (m.kind == CsDeclarationKind.field) m,
    ];
    final out = [
      ...head,
      'type ${d.name}${_goTypeParameters(typeParameters)} struct {',
    ];
    for (final (i, m) in fields.indexed) {
      _plainField(d.name, m);
      if (i > 0) out.add('');
      out
        ..addAll(_doc(m, indent: '\t'))
        ..add('\t${_exported(m.name)} ${types.of(m.declaredType ?? 'Object')}');
    }
    out.add('}');
    final receiver = typeParameters.isEmpty
        ? '*${d.name}'
        : '*${d.name}[${typeParameters.join(', ')}]';
    for (final m in members) {
      if (m.kind != CsDeclarationKind.method) continue;
      final b = m.bodies.where((b) => b.name == m.name).firstOrNull;
      if (b == null) continue;
      final record = file.steps
          .where((r) => r.owner == d.name && r.body == m.name)
          .firstOrNull;
      out
        ..add('')
        ..addAll(_doc(m, indent: ''))
        ..add('func (s $receiver) ${_signature(m.name, b, types)} {');
      if (record?.steps case final steps?) {
        final collaborator = fields
            .where((f) => f.name == 'collaborator')
            .firstOrNull
            ?.declaredType;
        if (collaborator == null) {
          throw IrMapException(
            '${file.file.path}: ${d.name}.${m.name} has steps but its class '
            'no `collaborator` field',
          );
        }
        final value = types.resultOf(b.returnType);
        final writer = _StepWriter(
          collaborator: collaborator.replaceAll('?', ''),
          symbols: symbols,
          value: value,
        );
        final lines = [
          ...writer.write(steps, '\t'),
          if (!writer.endsInReturn(steps)) '\t${writer.done}',
        ];
        out.addAll([if (writer.needsZero) '\tvar zero $value', ...lines]);
      } else {
        out.add(_notImplemented(b, m, types));
      }
      out.add('}');
    }
    return out;
  }

  /// The doc comment of [d]: its Dart doc text, then its back-links and
  /// markers (`irspecs_ir.md` §12) — the same section ids the Dart trio
  /// carries.
  List<String> _doc(CsDeclaration d, {required String indent}) {
    final lines = <String>[
      for (final l in d.docComment?.lines ?? const <String>[])
        _docLine(l.trimLeft().replaceFirst(RegExp(r'^/// ?'), '').trim()),
    ];
    final tags = <String>[
      if (d.codeSpec case final cs?)
        'codeSpec: ${cs.id}${cs.source.isEmpty ? '' : ' source: ${cs.source.join(', ')}'}',
      for (final r in d.docSpec ?? const <CsDocRef>[])
        'docSpec: ${r.sectionId} — ${r.description}',
      for (final m in d.markers) 'cs: ${_marker(m)}',
      for (final a in d.annotations) 'dart: ${a.source}',
    ];
    if (lines.isEmpty && tags.isEmpty) return const [];
    final all = [
      ...lines,
      if (lines.isNotEmpty && tags.isNotEmpty) '',
      ...tags,
    ];
    return [for (final l in all) l.isEmpty ? '$indent//' : '$indent// $l'];
  }

  /// A doc line as gofmt keeps it: a list item is indented as gofmt writes
  /// one.
  String _docLine(String line) {
    if (RegExp(r'^[-*+] ').hasMatch(line)) return '  - ${line.substring(2)}';
    return line;
  }

  String _marker(CsMarker m) {
    String v(CsValue x) => switch (x) {
      CsStringValue(:final value) => jsonEncode(value),
      CsBoolValue(:final value) => '$value',
      CsIntValue(:final value) => '$value',
      CsNullValue() => 'null',
      CsQualifiedValue(:final prefix, :final name) => '$prefix.$name',
      CsListValue(:final values) => '[${values.map(v).join(', ')}]',
      CsConstructionValue(:final type, :final positional, :final named) =>
        '$type(${[...positional.map(v), for (final MapEntry(:key, :value) in named.entries) '$key: ${v(value)}'].join(', ')})',
      CsUnknownValue(:final source) => source,
    };
    return '${m.name}(${[...m.positional.map(v), for (final MapEntry(:key, :value) in m.named.entries) '$key: ${v(value)}'].join(', ')})';
  }
}

/// A 3b body from its steps (`irspecs_ir.md` §4.7): every collaborator call
/// takes the context and returns an error, a guard a bool and an error.
class _StepWriter {
  final String collaborator;
  final _Symbols symbols;

  /// The body's value type; `null` when it returns only an error.
  final String? value;

  bool needsZero = false;
  int _guards = 0;

  _StepWriter({
    required this.collaborator,
    required this.symbols,
    required this.value,
  });

  String get _fail {
    if (value == null) return 'return err';
    needsZero = true;
    return 'return zero, err';
  }

  bool _returnsValue(String method) {
    final b = symbols.methods['$collaborator.$method'];
    if (b == null) {
      throw IrMapException(
        'the step calls $collaborator.$method, which the collaborator does '
        'not declare',
      );
    }
    final t = (b.returnType ?? 'void').replaceAll(' ', '');
    return !(t == 'void' || t == 'Future<void>' || t == 'Future');
  }

  String _call(String method, List<String> args) =>
      's.Collaborator.${_exported(method)}('
      '${['ctx', ...args.map(_local)].join(', ')})';

  /// The return that ends a body successfully.
  String get done {
    if (value == null) return 'return nil';
    needsZero = true;
    return 'return zero, nil';
  }

  bool endsInReturn(List<IrStep> steps) =>
      steps.isNotEmpty && steps.last is IrReturnStep;

  List<String> write(List<IrStep> steps, String indent) => [
    for (final s in steps)
      ...switch (s) {
        IrCallStep(:final method, :final arguments) => [
          '${indent}if ${_returnsValue(method) ? '_, ' : ''}err := '
              '${_call(method, arguments)}; err != nil {',
          '$indent\t$_fail',
          '$indent}',
        ],
        IrReturnStep(:final method, :final arguments) => [
          if (method == null)
            '$indent$done'
          else
            '${indent}return ${_call(method, arguments)}',
        ],
        IrGuardedStep(:final guard, :final arguments, :final steps) => () {
          final applies = 'applies${++_guards}';
          return [
            '$indent$applies, err := ${_call(guard, arguments)}',
            '${indent}if err != nil {',
            '$indent\t$_fail',
            '$indent}',
            '${indent}if $applies {',
            ...write(steps, '$indent\t'),
            '$indent}',
          ];
        }(),
      },
  ];
}

List<String> _importBlock(Set<String> imports, String module) {
  if (imports.isEmpty) return const [];
  final std = [
    for (final i in imports)
      if (!i.startsWith('$module/') && !i.contains('.')) i,
  ]..sort();
  final external = [
    for (final i in imports)
      if (!i.startsWith('$module/') && i.contains('.')) i,
  ]..sort();
  final local = [
    for (final i in imports)
      if (i.startsWith('$module/')) i,
  ]..sort();
  final groups = [
    for (final g in [std, external, local])
      if (g.isNotEmpty) [for (final i in g) '\t"$i"'],
  ];
  return [
    '',
    'import (',
    for (final (n, g) in groups.indexed) ...[if (n > 0) '', ...g],
    ')',
  ];
}

