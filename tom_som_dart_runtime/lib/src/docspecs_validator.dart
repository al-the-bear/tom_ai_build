/// Consolidated DocSpecs parsing + validation (SOM §14): the embedded,
/// runtime-owned equivalent of the `tom_doc_scanner` + `tom_doc_specs` split,
/// redesigned as one coherent API. This is the reference implementation the
/// other eight language runtimes port; the Dart violation messages are the
/// golden reference — every port must produce the same `rule` / `sectionId` /
/// `line` triples.
///
/// Three capabilities, one module:
///
///  1. **Parse** — [DocSpecsDocument.parse] reads any DocSpecs `*.md`
///     *schema-free* into a generic section tree ([DocSpecsSection]): ids,
///     titles, heading levels, body text, source lines. Fenced code blocks
///     shield their lines from heading detection ([MarkdownFenceTracker], the
///     exact semantics of the [SpecDocumentMarkdown] codec).
///  2. **Validate** — [DocSpecsValidator.validate] checks a parsed document
///     against a [DocSpecsSchema] (a `*.docspecs-schema.yaml` as generated by
///     the schema generator , SOM §13) and returns a structured
///     [DocSpecsViolation] list. Validation **never fails fast** — the full
///     list is always produced; a document is valid iff the list is empty.
///  3. **Bind** — [bindDocSpecsMarkdown] maps the same markdown onto the SOM
///     metadata tree, delegating to [SpecDocumentMarkdown.parse] (SOM §11.7).
///
/// Supported schema features (the SOM §14 scope): section-types (`prefix`,
/// `pattern-check-id`, `subsection-types` with `min-count`/`max-count`,
/// `format`, `text-required`, `min-text-length`/`max-text-length`,
/// `description`), form-types (fields with `required` and `pattern-check`),
/// and the `document:` structure (top-level sections, `optional`).
/// `validation-prompt` values are carried as data. Anything else — generator
/// placeholders, database-schema sections, custom tags — is **ignored on
/// load** and named in [DocSpecsSchema.warnings]; nothing is silently
/// dropped.
library;

import 'package:yaml/yaml.dart';

import 'spec_document.dart';
import 'spec_document_markdown.dart';
import 'spec_model.dart';
import 'spec_notation.dart';

/// The SOM §14 violation rule vocabulary — identical across all nine runtimes.
enum DocSpecsViolationRule {
  /// A heading's id resolves to no section-type, or to a type not allowed at
  /// its nesting position.
  unknownSection,

  /// A required section (document slot or `min-count >= 1` subsection) has no
  /// occurrence.
  missingRequiredSection,

  /// A section id fails its type's `pattern-check-id`.
  idPatternMismatch,

  /// A subsection occurs, but fewer times than its `min-count`.
  tooFewItems,

  /// A subsection occurs more times than its numeric `max-count`.
  tooManyItems,

  /// A `required` form field is absent (or empty) in a form-formatted section.
  missingRequiredField,

  /// A form field value fails its `pattern-check`.
  fieldPatternMismatch,

  /// A `text-required` section has no body text.
  textRequired,

  /// A section's body text length is outside `min-text-length` /
  /// `max-text-length`.
  textLengthOut,

  /// The document/root shape does not match — wrong root id vs `title-format`,
  /// or a non-form `format` section without the demanded fenced block.
  formatMismatch,

  /// A heading line without a parseable `<!--[SECTION-ID]-->` comment.
  malformedHeading,

  // The reading notation's findings (DocSpecs specification, Reading
  // Notation RN-10), reported by [scanNotation] per value: a section's own
  // body, and in a TomSpecs rendition each form field's value apart.

  /// An opening fence has no closing fence in the same value (TomSpecs) or
  /// before the next heading (any other document).
  unclosedDiv,

  /// A closing fence has no open div.
  strayClosingFence,

  /// A span's attribute braces open after `]` and do not close on the
  /// paragraph.
  unclosedSpan,

  /// A div's attributes hold no class (TomSpecs renditions only).
  divWithoutKind,

  /// A div's or span's kind is not registered (TomSpecs renditions only). The
  /// one warning: [DocSpecsViolation.isWarning].
  unknownKind,

  /// An inline review mark opens inside a span or citation and closes outside
  /// it, or the reverse.
  markAcrossNotation,

  /// A comment or question block stands inside a div.
  annotationInsideDiv,

  /// A div stands inside a comment or question block.
  divInsideAnnotation,

  /// A `rejected` div is present.
  rejectedBlock,

  /// A table, list body or form field is malformed (the DocSpecs
  /// specification's *Findings in list bodies and tables*): a form, section
  /// or record table without a matching delimiter row, a row of another cell
  /// count, a field given twice (the first occurrence kept), a `refs` or
  /// `records` div beside other text or item headings, a `records` div
  /// holding no table or one whose first column is not `Id`, an unclosed
  /// `refs` / `records` fence.
  malformedBlock,

  /// A form-table row or a record-table column names no field of its form.
  unknownField,
}

/// One structured violation (SOM §14): the [rule], the offending [sectionId]
/// (when one exists), the bound runtime [path] (when resolvable), the 1-based
/// source [line], and a human-readable [message].
class DocSpecsViolation {
  /// [rule], [line] and [message] are required — they are the three every
  /// violation can always state, since even a heading too malformed to yield
  /// an id still occupies a source line.
  ///
  /// [sectionId] and [path] are optional because each may genuinely not
  /// exist: a `malformedHeading` has no id to name, and this validator works
  /// on Markdown alone, so it never resolves a document [path] itself —
  /// `validateSpecDocument` does, for a SOM document it renders.
  DocSpecsViolation({
    required this.rule,
    required this.line,
    required this.message,
    this.sectionId,
    this.path,
  });

  /// Which rule was broken. This — not [message] — is the machine-readable
  /// verdict, and it is part of the cross-runtime contract: all nine
  /// languages must report the same rule for the same document, so a
  /// consumer that branches on the prose instead will diverge between ports.
  final DocSpecsViolationRule rule;

  /// The DocSpecs id of the offending section, or `null` when none is
  /// available (a malformed heading, or an empty document).
  ///
  /// For a cardinality or required-subsection finding this names the
  /// **parent** — the section whose child count is wrong — because the
  /// missing child has no id to point at.
  final String? sectionId;

  /// The SOM document path the finding is about, when one is resolvable.
  /// `null` from [DocSpecsValidator.validate], which works schema-to-markdown
  /// and never consults a document; `validateSpecDocument` renders a SOM
  /// document itself and fills it from the renderer's heading map.
  ///
  /// **Not dead, and not removable.** It is a member of the SOM §14 violation
  /// structure, which is specified as uniform across the nine runtimes — Rust,
  /// Java and C all declare it, and all nine render it the same way, so
  /// dropping it from Dart would desync the reference implementation from the
  /// eight ports measured against it. That every violation *this tier* raises
  /// leaves it `null` is a property of the tier, not of the field.
  final String? path;

  /// The **1-based** source line, so it can be handed to an editor unchanged.
  ///
  /// It points at the *heading* of the section at fault rather than at the
  /// offending body line, with one exception: a `fieldPatternMismatch`
  /// points at the form field's own line when that line was seen.
  final int line;

  /// The human-readable explanation. Display text only — it is deliberately
  /// not stable API, and an authored `error-message` on the failing
  /// pattern-check replaces the generated wording when one exists.
  final String message;

  /// Whether the finding is a warning rather than an error: only
  /// [DocSpecsViolationRule.unknownKind] is. A warning does not make a
  /// document invalid.
  bool get isWarning => rule == DocSpecsViolationRule.unknownKind;

  @override
  String toString() =>
      'line $line: ${rule.name}${sectionId != null ? ' [$sectionId]' : ''}'
      '${path != null ? ' ($path)' : ''} — $message';
}

// ---------------------------------------------------------------------------
// 1. Generic (schema-free) markdown parse
// ---------------------------------------------------------------------------

/// One section of a schema-free DocSpecs parse: its [id] (null for a
/// malformed heading), heading [title], markdown [level], 1-based heading
/// [line], accumulated [bodyLines] (each with its own source line =
/// [bodyStartLine] + index), and nested [children].
class DocSpecsSection {
  /// All four arguments are required, [id] included even though it is
  /// nullable: a heading always has a position and a title, and whether it
  /// carries an id is exactly the fact the parse has to record, so leaving it
  /// unstated is never right. [bodyLines] and [children] are filled in by
  /// [DocSpecsDocument.parse] as it walks past the heading.
  DocSpecsSection({
    required this.id,
    required this.title,
    required this.level,
    required this.line,
  });

  /// The `<!--[SECTION-ID]-->` machine identity, or `null` when the heading
  /// carried no such comment (SOM §11.2).
  ///
  /// `null` is not merely "unknown": it has already been reported as a
  /// [DocSpecsViolationRule.malformedHeading] by the parse, which is why the
  /// validator skips such a section silently instead of reporting it twice.
  final String? id;

  /// The heading text with the id comment stripped — the section's headline.
  /// Never `null`: a heading with only an id comment yields the empty string.
  ///
  /// Note that the id, not this, is the identity; the title is authored prose
  /// and no rule in this validator matches on it.
  final String title;

  /// The markdown heading depth (`#` = 1). **Uncapped** — SOM §11.2 makes
  /// depth 1 + section depth with no ceiling and requires DocSpecs tooling to
  /// accept `#{7,}`, so a reader must not assume the CommonMark limit of 6.
  ///
  /// Nesting is derived from this alone: the parse pops its stack until the
  /// top is shallower, so a skipped level nests rather than erroring.
  final int level;

  /// The **1-based** source line of the heading itself. Every violation
  /// raised against this section reports this line, so it is what an editor
  /// jumps to.
  final int line;

  /// The raw body lines directly under this heading (before any child
  /// heading), in source order.
  final List<String> bodyLines = [];

  /// The source line of the first body line (heading line + 1).
  int get bodyStartLine => line + 1;

  /// The directly nested sections, in source order.
  ///
  /// Order is load-bearing for the reader, not for validation: cardinality is
  /// counted per section-type name, so the same type may appear repeatedly
  /// and interleaved with others without that alone being a violation. It is
  /// the *counts*, matched against the parent type's `subsection-types`, that
  /// decide.
  final List<DocSpecsSection> children = [];

  /// The trimmed body text (leading/trailing blank lines removed).
  String get text {
    var start = 0;
    var end = bodyLines.length;
    while (start < end && bodyLines[start].trim().isEmpty) {
      start++;
    }
    while (end > start && bodyLines[end - 1].trim().isEmpty) {
      end--;
    }
    return bodyLines.sublist(start, end).join('\n');
  }
}

/// A schema-free DocSpecs markdown parse: the declared schema header (if
/// any), the top-level [sections], and the parse-time [violations]
/// (malformed headings). Validation against a schema is a separate step —
/// [DocSpecsValidator.validate] — which folds these violations into its
/// result.
class DocSpecsDocument {
  DocSpecsDocument._();

  /// The `<!-- docspec: schema-id/version -->` declaration, when present.
  String? declaredSchema;

  /// Top-level (usually one: the document root) sections in source order.
  final List<DocSpecsSection> sections = [];

  /// Parse-time violations: [DocSpecsViolationRule.malformedHeading] for each
  /// heading without a `<!--[SECTION-ID]-->` comment.
  final List<DocSpecsViolation> violations = [];

  static final RegExp _docspecHeader = RegExp(
    r'^<!--\s*docspec:\s*(\S+)\s*-->\s*$',
  );

  /// Parses [text] into the generic section tree. Any markdown is accepted;
  /// structural problems surface as [violations], never as exceptions.
  static DocSpecsDocument parse(String text) {
    final doc = DocSpecsDocument._();
    final fence = MarkdownFenceTracker();
    final stack = <DocSpecsSection>[];
    final lines = text.split('\n');
    var readable = false;
    for (var i = 0; i < lines.length; i++) {
      final raw = lines[i];
      final lineNo = i + 1;
      final trimmed = raw.trimRight();
      if (!fence.inFence) {
        if (stack.isEmpty && doc.declaredSchema == null) {
          final d = _docspecHeader.firstMatch(trimmed);
          if (d != null) {
            doc.declaredSchema = d.group(1);
            continue;
          }
        }
        // A stripped rendition (SOM §11.1): its readable header stands before
        // the root heading, and its appendix after the marker is not part of
        // the document.
        if (stack.isEmpty &&
            SpecDocumentMarkdown.readableComment.hasMatch(trimmed)) {
          readable = true;
          continue;
        }
        if (readable && trimmed == SpecDocumentMarkdown.appendixMarker) {
          break;
        }
        final h = SpecDocumentMarkdown.headingLine.firstMatch(trimmed);
        final div = h == null ? _styledDivHeading(trimmed) : null;
        if (h != null || div != null) {
          final level = h != null ? h.group(1)!.length : div!.$1;
          final rest = h != null ? h.group(2)!.trim() : div!.$2.trim();
          final c = SpecDocumentMarkdown.headlineComment.firstMatch(rest);
          final id = c?.group(1);
          final section = DocSpecsSection(
            id: id,
            // group(2) is the optional key=value region (codespecs_mapping.md
            // §9.2 codeSpec); the title is group(3), the section's own anchor
            // removed (Section Anchors). For a bare heading with no comment,
            // the whole rest is the title.
            title: c != null ? stripOwnAnchor(c.group(3)!.trim(), id!) : rest,
            level: level,
            line: lineNo,
          );
          if (c == null) {
            doc.violations.add(
              DocSpecsViolation(
                rule: DocSpecsViolationRule.malformedHeading,
                line: lineNo,
                message:
                    'heading "$rest" carries no <!--[SECTION-ID]--> '
                    'headline comment',
              ),
            );
          }
          while (stack.isNotEmpty && stack.last.level >= level) {
            stack.removeLast();
          }
          (stack.isEmpty ? doc.sections : stack.last.children).add(section);
          stack.add(section);
          continue;
        }
      }
      if (stack.isNotEmpty) stack.last.bodyLines.add(raw);
      fence.feed(raw);
    }
    return doc;
  }

  /// A styled-div heading (the DocSpecs specification's *Styled-div
  /// headings*): a whole line `<div class="heading<N>" …>…</div>` at column
  /// 0 with N ≥ 7 reads as a heading of level N whose text is the div's inner
  /// text with `&amp;`, `&lt;`, `&gt;` decoded. Returns (level, text), or
  /// `null` for any other line — a `heading<N>` div with N ≤ 6 is content.
  static (int, String)? _styledDivHeading(String line) {
    final m = _styledDiv.firstMatch(line);
    if (m == null) return null;
    final level = int.parse(m.group(1)!);
    if (level < 7) return null;
    final text = m
        .group(2)!
        .replaceAll('&lt;', '<')
        .replaceAll('&gt;', '>')
        .replaceAll('&amp;', '&');
    return (level, text);
  }

  static final RegExp _styledDiv = RegExp(
    r'^<div class="heading([0-9]+)"[^>]*>(.*)</div>$',
  );

  static final RegExp _anchor = RegExp(r'^<a id="([^"]*)"></a>\s*');

  /// [text] with a leading anchor `<a id="ID"></a>` removed when its id is
  /// [id] (Section Anchors): the section's own anchor stores nothing. Any
  /// other anchor is ordinary text and stays.
  static String stripOwnAnchor(String text, String id) {
    final m = _anchor.firstMatch(text);
    return m != null && m.group(1) == id ? text.substring(m.end) : text;
  }

  /// Every section with an id, depth-first in source order.
  Iterable<DocSpecsSection> get allSections sync* {
    Iterable<DocSpecsSection> walk(List<DocSpecsSection> list) sync* {
      for (final s in list) {
        yield s;
        yield* walk(s.children);
      }
    }

    yield* walk(sections);
  }

  /// Returns [text] with the body of the section whose id is [sectionId]
  /// replaced by [body]; every other byte is kept.
  ///
  /// The body is the section's **own** region: the lines after its heading up
  /// to its first child heading, or the next heading of any level. The heading
  /// line (with its `<!--[ID]-->` comment) and the subsections are untouched.
  /// The region is found by the same fence-aware [parse], so a `#` line inside
  /// a fenced block is never taken for a heading.
  ///
  /// The new region is a blank line, [body] with its leading and trailing
  /// blank lines removed, and a blank line; an empty [body] leaves a single
  /// blank line. Throws [ArgumentError] when [sectionId] names no section or
  /// more than one, and when [body] would change the document's structure: a
  /// heading outside a fenced block, or a fence it opens and never closes.
  static String replaceSectionBody(String text, String sectionId, String body) {
    final matches = parse(
      text,
    ).allSections.where((s) => s.id == sectionId).toList();
    if (matches.isEmpty) {
      throw ArgumentError.value(sectionId, 'sectionId', 'names no section');
    }
    if (matches.length > 1) {
      throw ArgumentError.value(
        sectionId,
        'sectionId',
        'names ${matches.length} sections (lines '
            '${matches.map((s) => s.line).join(', ')})',
      );
    }

    var bodyLines = body.split('\n');
    while (bodyLines.isNotEmpty && bodyLines.first.trim().isEmpty) {
      bodyLines = bodyLines.sublist(1);
    }
    while (bodyLines.isNotEmpty && bodyLines.last.trim().isEmpty) {
      bodyLines = bodyLines.sublist(0, bodyLines.length - 1);
    }
    final fence = MarkdownFenceTracker();
    for (final line in bodyLines) {
      if (!fence.inFence &&
          (SpecDocumentMarkdown.headingLine.hasMatch(line.trimRight()) ||
              _styledDivHeading(line.trimRight()) != null)) {
        throw ArgumentError.value(
          body,
          'body',
          'contains a heading outside a fenced block: "$line"',
        );
      }
      fence.feed(line);
    }
    if (fence.inFence) {
      throw ArgumentError.value(body, 'body', 'leaves a fenced block open');
    }

    final section = matches.single;
    final lines = text.split('\n');
    final start = section.line; // 0-based index of the first body line
    final end = start + section.bodyLines.length;
    final region = bodyLines.isEmpty ? [''] : ['', ...bodyLines, ''];
    return [
      ...lines.sublist(0, start),
      ...region,
      ...lines.sublist(end),
    ].join('\n');
  }
}

