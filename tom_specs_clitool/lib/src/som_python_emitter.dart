/// Emits the generated Python typed object model (`tom_som_python_v0`) from a
/// resolved [SpecModel].
///
/// The generated classes are an **editing facade** over the generic
/// `tom_som_python_runtime` `SpecDocument`: every typed accessor delegates to
/// the path-keyed memory representation, so a typed mutation is visible through
/// the generic path and vice-versa (spec §3). Each document-root class performs
/// the **instantiation-time version check** (`check_som_model_version`) against
/// the document's authoring stamp (§2.2) and exposes its own generated model
/// version (§2.1).
///
/// This is the Python counterpart of [SomDartEmitter] — the same reachability
/// walk, the same deterministic ordering, the same field-kind mapping — only the
/// emitted surface syntax differs (Python ``@property`` accessors over the
/// shared `tom_som_runtime` facade base classes).
library;

import 'package:tom_som_dart_runtime/tom_som_dart_runtime.dart';

/// Generates the `tom_som_python_v0` package module source for a [SpecModel].
class SomPythonEmitter {
  final SpecModel model;
  final SpecReflection _ref;

  /// The version label of the generated project (`v0`, `v1`, …); names the
  /// `tom_som_<slug>_<label>` output project. It no longer drives the reported
  /// model version — see [modelVersionString].
  final String versionLabel;

  /// The document-root type names to generate. Empty ⇒ every root in the model.
  final List<String> documentRoots;

  SomPythonEmitter(
    this.model, {
    this.versionLabel = 'v0',
    this.documentRoots = const [],
  }) : _ref = SpecReflection(model);

  /// The model version the generated object model reports (§2.1), `major.minor`,
  /// taken from the model's own version stamp (the `tom_specs_model` project
  /// version), not the project [versionLabel] — which only names the `_vN`
  /// output project.
  String get modelVersionString => model.modelVersionString;

  /// The roots to generate, resolved against [documentRoots] (empty ⇒ all).
  List<SpecRoot> get _selectedRoots {
    if (documentRoots.isEmpty) return model.roots;
    final wanted = documentRoots.toSet();
    return model.roots.where((r) => wanted.contains(r.type)).toList();
  }

  /// Generated form-class names allocated so far in the current
  /// [generateLibrary] run, used to keep them globally unique. Reset at the
  /// start of every run so output stays deterministic.
  final Set<String> _usedFormNames = {};

  /// Returns a unique form-class name for [base], appending the smallest
  /// numeric suffix (`2`, `3`, …) that is not yet taken when [base] collides.
  String _allocFormName(String base) {
    if (_usedFormNames.add(base)) return base;
    var n = 2;
    while (!_usedFormNames.add('$base$n')) {
      n++;
    }
    return '$base$n';
  }

  /// Builds the complete generated module as a single Python source string.
  String generateLibrary() {
    _usedFormNames.clear();
    final rootTypes = _selectedRoots.map((r) => r.type).toSet();
    final reachable = _reachableClasses(rootTypes);
    final enums = _reachableEnums(reachable);
    final formClasses = <_FormClass>[];

    final classBlocks = <String>[];
    for (final name in reachable.toList()..sort()) {
      final cls = model.classNamed(name);
      if (cls == null) continue;
      classBlocks.add(_emitClass(cls,
          isRoot: rootTypes.contains(name),
          collectForm: (fc) => formClasses.add(fc)));
    }

    final buffer = StringBuffer()
      ..writeln('# GENERATED by tom_specs_clitool SomPythonEmitter '
          '($versionLabel) — do not edit by hand.')
      ..writeln('"""Typed object-model facade over the generic '
          '`tom_som_runtime` document."""')
      ..writeln()
      ..writeln('from __future__ import annotations')
      ..writeln();

    if (enums.isNotEmpty) {
      buffer.writeln('from enum import Enum');
    }
    buffer
      ..writeln('from tom_som_runtime import (')
      ..writeln('    SomList,')
      ..writeln('    SomNode,')
      ..writeln('    SomScalar,')
      ..writeln('    SpecDocument,')
      ..writeln('    check_som_model_version,')
      ..writeln(')')
      ..writeln();

    for (final e in enums) {
      buffer
        ..write(_emitEnum(e))
        ..writeln();
    }
    for (final block in classBlocks) {
      buffer
        ..write(block)
        ..writeln();
    }
    for (final fc in formClasses..sort((a, b) => a.name.compareTo(b.name))) {
      buffer
        ..write(fc.source)
        ..writeln();
    }
    return buffer.toString();
  }

  // --- reachability -------------------------------------------------------

  Set<String> _reachableClasses(Set<String> rootTypes) {
    final visited = <String>{};
    final queue = <String>[...rootTypes];
    while (queue.isNotEmpty) {
      final name = queue.removeLast();
      if (!visited.add(name)) continue;
      final cls = model.classNamed(name);
      if (cls == null) continue;
      for (final f in cls.fields) {
        switch (f.kind) {
          case SpecFieldKind.complex:
          case SpecFieldKind.section:
            if (f.type != null) queue.add(f.type!);
            break;
          case SpecFieldKind.list:
            if (f.elementIsComplex && f.elementType != null) {
              queue.add(f.elementType!);
            }
            break;
          case SpecFieldKind.form:
          case SpecFieldKind.content:
          case SpecFieldKind.enumValue:
          case SpecFieldKind.scalar:
            break;
        }
      }
    }
    return visited;
  }

  /// The distinct enum types referenced by reachable classes, with their values.
  List<_EnumType> _reachableEnums(Set<String> reachable) {
    final byName = <String, _EnumType>{};
    for (final name in reachable) {
      final cls = model.classNamed(name);
      if (cls == null) continue;
      for (final f in cls.fields) {
        if (f.kind == SpecFieldKind.enumValue && f.enumType != null) {
          byName.putIfAbsent(
              f.enumType!, () => _EnumType(f.enumType!, f.enumValues));
        }
      }
    }
    final result = byName.values.toList()
      ..sort((a, b) => a.name.compareTo(b.name));
    return result;
  }

  // --- emit ---------------------------------------------------------------

  String _emitEnum(_EnumType e) {
    final b = StringBuffer()
      ..writeln('class ${e.name}(Enum):')
      ..writeln('    """Generated enum for `${e.name}` values."""')
      ..writeln();
    for (final v in e.values) {
      // The member *value* carries the original token (the Dart constant name);
      // the member *identifier* may be keyword-sanitised, so parsing/encoding
      // round-trips through `.value`, not `.name` (keeps the stored token
      // identical to the Dart path — see `_acc`).
      b.writeln('    ${_acc(v)} = "${_pystr(v)}"');
    }
    b
      ..writeln()
      ..writeln()
      ..writeln('def _parse_${e.name}(token):')
      ..writeln('    """Parses a stored token into a ${e.name}, or None."""')
      ..writeln('    if not token:')
      ..writeln('        return None')
      ..writeln('    for v in ${e.name}:')
      ..writeln('        if v.value == token:')
      ..writeln('            return v')
      ..writeln('    return None');
    return b.toString();
  }

  String _emitClass(
    SpecClass cls, {
    required bool isRoot,
    required void Function(_FormClass) collectForm,
  }) {
    final b = StringBuffer();
    b.writeln('class ${cls.name}(SomNode):');
    _writeDoc(b, cls.doc, '    ');

    if (isRoot) {
      final root = model.roots.firstWhere((r) => r.type == cls.name);
      final seg = _ref.rootSegment(root);
      b
        ..writeln('    #: The model version this object model was generated '
            'against (§2.1).')
        ..writeln("    model_version = '$modelVersionString'")
        ..writeln()
        ..writeln('    def __init__(self, doc, document_version=None):')
        ..writeln('        super().__init__(doc, "${_pystr(seg)}")')
        ..writeln('        check_som_model_version('
            '${cls.name}.model_version, document_version)')
        ..writeln()
        ..writeln('    @classmethod')
        ..writeln('    def load_yaml(cls, yaml):')
        ..writeln('        """Loads a `*.docspecs.yaml` document and returns the '
            'typed root with the')
        ..writeln("        document's authoring stamp already applied (§ item 4) "
            '— one call for')
        ..writeln('        the former decode → load_json → thread-'
            '`document_version` sequence."""')
        ..writeln('        doc = SpecDocument.from_yaml(yaml)')
        ..writeln('        return cls(doc, document_version=doc.model_version)')
        ..writeln()
        ..writeln('    @classmethod')
        ..writeln('    def load_file(cls, path):')
        ..writeln('        """Loads a `*.docspecs.yaml` document from the file at '
            '*path* — the file')
        ..writeln('        companion to :meth:`load_yaml`."""')
        ..writeln('        doc = SpecDocument.from_file(path)')
        ..writeln('        return cls(doc, document_version=doc.model_version)')
        ..writeln()
        ..writeln('    @property')
        ..writeln('    def object_model_version(self):')
        ..writeln("        \"\"\"This object model's own model version "
            "(major.minor), per §2.1.\"\"\"")
        ..writeln('        return ${cls.name}.model_version');
    } else {
      b
        ..writeln('    def __init__(self, doc, path):')
        ..writeln('        super().__init__(doc, path)');
    }

    var emittedField = false;
    for (final f in cls.fields) {
      b.writeln();
      _writeField(b, cls, f, collectForm);
      emittedField = true;
    }
    if (!emittedField) {
      // A class with no fields still needs a body; __init__ already provided it.
    }
    return b.toString();
  }

  void _writeField(
    StringBuffer b,
    SpecClass cls,
    SpecField f,
    void Function(_FormClass) collectForm,
  ) {
    final seg = _ref.fieldSegment(f);
    final childPath = 'f"{self.path}/${_fstr(seg)}"';
    // Python-safe accessor identifier (the path segment above is untouched).
    final acc = _acc(f.name);
    switch (f.kind) {
      case SpecFieldKind.content:
      case SpecFieldKind.scalar:
        _emitStringProperty(b, acc, childPath, f.doc);
        break;
      case SpecFieldKind.enumValue:
        if (f.enumType == null) {
          _emitStringProperty(b, acc, childPath, f.doc);
        } else {
          final et = f.enumType!;
          _writeComment(b, f.doc, '    ');
          b
            ..writeln('    @property')
            ..writeln('    def $acc(self):')
            ..writeln('        return _parse_$et(self.doc.content($childPath))')
            ..writeln()
            ..writeln('    @$acc.setter')
            ..writeln('    def $acc(self, value):')
            ..writeln('        self.doc.set_content($childPath, '
                'value.value if value is not None else "")');
        }
        break;
      case SpecFieldKind.complex:
      case SpecFieldKind.section:
        final target = f.type;
        _writeComment(b, f.doc, '    ');
        if (target == null) {
          b
            ..writeln('    @property')
            ..writeln('    def $acc(self):')
            ..writeln('        return None  # (skipped: no target type)');
        } else {
          b
            ..writeln('    @property')
            ..writeln('    def $acc(self):')
            ..writeln('        return $target(self.doc, $childPath)');
        }
        break;
      case SpecFieldKind.list:
        _writeComment(b, f.doc, '    ');
        // A pattern-bearing list passes its `@SectionIdPattern` so the facade
        // can auto-generate section ids on `add` (AA1 criteria 3–5); a scalar
        // list omits it (pattern-less, `add` ignores id args).
        final patternArg = f.sectionIdPattern != null
            ? ", pattern=\"${_pystr(f.sectionIdPattern!)}\""
            : '';
        if (f.elementIsComplex && f.elementType != null) {
          final et = f.elementType!;
          b
            ..writeln('    @property')
            ..writeln('    def $acc(self):')
            ..writeln('        return SomList(self.doc, $childPath, '
                'lambda d, p: $et(d, p)$patternArg)');
        } else {
          b
            ..writeln('    @property')
            ..writeln('    def $acc(self):')
            ..writeln('        return SomList(self.doc, $childPath, '
                'lambda d, p: SomScalar(d, p)$patternArg)');
        }
        break;
      case SpecFieldKind.form:
        final formName = _allocFormName('${cls.name}${_pascal(f.name)}Form');
        collectForm(_FormClass(formName, _emitFormClass(formName, f)));
        _writeComment(b, f.doc, '    ');
        b
          ..writeln('    @property')
          ..writeln('    def $acc(self):')
          ..writeln('        return $formName(self.doc, $childPath)');
        break;
    }
  }

  void _emitStringProperty(
      StringBuffer b, String name, String childPath, String? doc) {
    _writeComment(b, doc, '    ');
    b
      ..writeln('    @property')
      ..writeln('    def $name(self):')
      ..writeln('        return self.doc.content($childPath) or ""')
      ..writeln()
      ..writeln('    @$name.setter')
      ..writeln('    def $name(self, value):')
      ..writeln('        self.doc.set_content($childPath, value)');
  }

  String _emitFormClass(String name, SpecField f) {
    final b = StringBuffer()
      ..writeln('class $name(SomNode):')
      ..writeln('    """Generated form facade for the `${f.name}` '
          '@Form section."""')
      ..writeln()
      ..writeln('    def __init__(self, doc, path):')
      ..writeln('        super().__init__(doc, path)');
    for (final ff in f.formFields) {
      final field = '"${_pystr(ff.name)}"';
      // The form-field key string ($field) is preserved; only the Python
      // accessor identifier is keyword-sanitised.
      final acc = _acc(ff.name);
      b
        ..writeln()
        ..writeln('    @property')
        ..writeln('    def $acc(self):')
        ..writeln('        return self.doc.form_field(self.path, $field) or ""')
        ..writeln()
        ..writeln('    @$acc.setter')
        ..writeln('    def $acc(self, value):')
        ..writeln('        self.doc.set_form_field(self.path, $field, value)');
    }
    return b.toString();
  }

  void _writeDoc(StringBuffer b, String? doc, String indent) {
    if (doc == null || doc.trim().isEmpty) return;
    final lines = doc.trimRight().split('\n').map((l) => l.trimRight()).toList();
    if (lines.length == 1) {
      b.writeln('$indent"""${_docEscape(lines.first)}"""');
      return;
    }
    b.writeln('$indent"""${_docEscape(lines.first)}');
    for (var i = 1; i < lines.length; i++) {
      b.writeln('$indent${_docEscape(lines[i])}');
    }
    b.writeln('$indent"""');
  }

  /// Emits a field's doc as `#` comment lines — field accessors carry their
  /// description as a comment, not a stray triple-quoted expression statement
  /// (only class/enum/form-class docs are real docstrings, which must be the
  /// first statement of their block).
  void _writeComment(StringBuffer b, String? doc, String indent) {
    if (doc == null || doc.trim().isEmpty) return;
    for (final line in doc.trimRight().split('\n')) {
      final text = line.trimRight();
      b.writeln(text.isEmpty ? '$indent#' : '$indent# $text');
    }
  }

  /// Escapes a docstring line so a stray `"""` or trailing backslash cannot
  /// terminate the triple-quoted string early.
  String _docEscape(String s) =>
      s.replaceAll('\\', '\\\\').replaceAll('"""', r'\"\"\"');

  /// Escapes a value for a plain double-quoted Python string literal.
  String _pystr(String s) =>
      s.replaceAll('\\', '\\\\').replaceAll('"', '\\"');

  /// Escapes a value for embedding inside a double-quoted Python f-string: the
  /// string escapes plus doubled braces so `{`/`}` are treated as literals.
  String _fstr(String s) => _pystr(s).replaceAll('{', '{{').replaceAll('}', '}}');

  /// The Python 3 reserved keywords. Dart field and enum-constant names are
  /// otherwise valid Python identifiers, so these are the only names that need
  /// rewriting before they can appear as a `def`/`@property`/enum member.
  static const Set<String> _pyKeywords = {
    'False', 'None', 'True', 'and', 'as', 'assert', 'async', 'await', 'break',
    'class', 'continue', 'def', 'del', 'elif', 'else', 'except', 'finally',
    'for', 'from', 'global', 'if', 'import', 'in', 'is', 'lambda', 'nonlocal',
    'not', 'or', 'pass', 'raise', 'return', 'try', 'while', 'with', 'yield',
  };

  /// Returns a Python-safe identifier for [name].
  ///
  /// A Dart identifier that happens to be a Python keyword (`from`, `and`,
  /// `class`, …) cannot be emitted as a `def`/`@property`/enum member, so PEP 8's
  /// trailing-underscore convention is applied (`from` → `from_`). Only the
  /// emitted Python identifier changes — the document path segment and the
  /// stored enum token are derived independently and stay byte-identical to the
  /// Dart facade, so cross-language documents remain compatible.
  String _acc(String name) => _pyKeywords.contains(name) ? '${name}_' : name;

  String _pascal(String s) {
    final parts = s.split(RegExp(r'[_\s]+')).where((p) => p.isNotEmpty);
    return parts.map((p) => p[0].toUpperCase() + p.substring(1)).join();
  }
}

class _EnumType {
  final String name;
  final List<String> values;
  _EnumType(this.name, this.values);
}

class _FormClass {
  final String name;
  final String source;
  _FormClass(this.name, this.source);
}
