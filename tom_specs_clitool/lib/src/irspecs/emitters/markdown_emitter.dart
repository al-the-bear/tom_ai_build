/// The Markdown rendering of an IR document set (`irspecs_ir.md` §10.3): a
/// generated, read-only view for agents, processes and tools outside the
/// stack. The IR stays the source; nothing here is composed — every text is
/// the IR's own (a name, a marker argument, a doc comment line, a back-link's
/// description), set in a fixed layout.
///
/// One DocSpecs document (`irspecs-md/1.0`) per IR document, named like it
/// (`CE-DB_data_access.md`, `package.md`), and `index.md` listing the areas,
/// the generation units and the areas each unit holds.
library;

import 'package:path/path.dart' as p;
import 'package:tom_som_dart_runtime/tom_som_dart_runtime.dart'
    show CodeSpecsAreaCatalog, SpecGenerationUnit;

import '../../codespecs/cs_model.dart';
import '../ir_model.dart';
import '../ir_steps.dart';
import 'emit_common.dart';

/// The DocSpecs schema the rendered documents declare.
const String kIrMarkdownSchema = 'irspecs-md/1.0';

/// The file name of the index document.
const String kIrMarkdownIndex = 'index.md';

/// The Markdown rendering of [documents].
///
/// [catalog] names each area (its canonical id, which the file names and
/// titles carry). [units] is the specification's generation-unit register,
/// listed in the index; empty when no specification was given.
/// [specRendition] is the specification's Markdown rendition as a path
/// relative to the output folder: given, every back-link token links to it
/// (`<rendition>#<token>`).
IrEmission emitMarkdown(
  List<IrDocument> documents, {
  required CodeSpecsAreaCatalog catalog,
  List<SpecGenerationUnit> units = const [],
  String? specRendition,
}) {
  final areas = IrAreaIndex(catalog);
  final canonical = {for (final a in catalog.areas) a.code: a.canonicalId};
  final files = <String, String>{};
  for (final d in documents) {
    files[_mdName(areas, d.area)] = _AreaWriter(
      d,
      canonical[d.area],
      areas.fileNameOf(d.area),
      specRendition,
    ).render();
  }
  files[kIrMarkdownIndex] = _index(documents, areas, canonical, units);
  return IrEmission(files, const []);
}

/// The Markdown name of [area]'s document: the IR name with `.md`.
String _mdName(IrAreaIndex areas, String area) {
  final ir = areas.fileNameOf(area);
  return '${ir.substring(0, ir.length - '.ir.yaml'.length)}.md';
}

/// Inline code: the value in backticks, a longer fence when it holds one.
String _code(String s) {
  if (!s.contains('`')) return '`$s`';
  return '`` $s ``';
}

/// A table cell: pipes escaped, line breaks as spaces.
String _cell(String s) => s.replaceAll('|', r'\|').replaceAll('\n', ' ');

String _header() => '<!-- docspec: $kIrMarkdownSchema -->\n';

String _index(
  List<IrDocument> documents,
  IrAreaIndex areas,
  Map<String, String> canonical,
  List<SpecGenerationUnit> units,
) {
  final index = IrIndex(documents);
  final b = StringBuffer()
    ..write(_header())
    ..writeln('# <!--[irspecs_index]--> IR Specs: ${index.title}')
    ..writeln()
    ..writeln(
      'Generated by `irspecs emit --standard markdown` from the IR '
      '(`*.ir.yaml`), which stays the source. Not edited by hand.',
    )
    ..writeln()
    ..writeln('## <!--[areas]--> Areas')
    ..writeln()
    ..writeln('| Area | Canonical id | Document | IR document | Files |')
    ..writeln('|---|---|---|---|---|');
  for (final d in documents) {
    final md = _mdName(areas, d.area);
    b.writeln(
      '| ${d.area} | ${canonical[d.area] ?? ''} | [$md]($md) | '
      '${_code(areas.fileNameOf(d.area))} | ${d.files.length} |',
    );
  }
  b
    ..writeln()
    ..writeln('## <!--[projects]--> Projects')
    ..writeln()
    ..writeln('| Locus | Package |')
    ..writeln('|---|---|');
  for (final project in _projects(documents)) {
    b.writeln('| ${project.locus.name} | ${_code(project.packageName)} |');
  }
  b
    ..writeln()
    ..writeln('## <!--[units]--> Generation units')
    ..writeln();
  if (units.isEmpty) {
    b.writeln(
      'No generation-unit register was given (`--spec`). Without one the '
      'IR maps to the trio above with `dart-tom`.',
    );
  } else {
    b
      ..writeln('| Unit | Kind | Areas (mapper) | Emitters |')
      ..writeln('|---|---|---|---|');
    for (final u in units) {
      final mapped = [
        for (final m in u.mappings) '${m.area} (${m.mapping})',
      ].join(', ');
      b.writeln(
        '| ${_code(u.unitId)} | ${u.kind} | ${_cell(mapped)} | '
        '${_cell(u.emitters.join(', '))} |',
      );
    }
  }
  return b.toString();
}

List<IrProject> _projects(List<IrDocument> documents) {
  final seen = <CsLocus>{};
  return [
    for (final d in documents)
      for (final project in d.projects)
        if (seen.add(project.locus)) project,
  ];
}

class _AreaWriter {
  final IrDocument document;
  final String? canonicalId;
  final String irName;
  final String? specRendition;
  final _b = StringBuffer();

  _AreaWriter(this.document, this.canonicalId, this.irName, this.specRendition);

  String render() {
    final area = document.area;
    final title = area == kIrPackageArea
        ? 'package: the files no area claims'
        : '$area: ${canonicalId ?? area}';
    _b
      ..write(_header())
      ..writeln('# <!--[${area.replaceAll('-', '_')}]--> $title')
      ..writeln()
      ..writeln(
        'Generated by `irspecs emit --standard markdown` from '
        '${_code(irName)}, which stays the source. Not edited by hand.',
      )
      ..writeln()
      ..writeln('## <!--[projects]--> Projects')
      ..writeln()
      ..writeln('| Locus | Package |')
      ..writeln('|---|---|');
    for (final project in document.projects) {
      _b.writeln('| ${project.locus.name} | ${_code(project.packageName)} |');
    }
    _b
      ..writeln()
      ..writeln('## <!--[files]--> Files')
      ..writeln();
    if (document.files.isEmpty) _b.writeln('No file.\n');
    final index = IrIndex([document]);
    var fileNumber = 0;
    for (final file in document.files) {
      fileNumber++;
      _file(file, fileNumber, index);
    }
    return '${_b.toString().trimRight()}\n';
  }

  void _file(IrFile file, int n, IrIndex index) {
    final cs = file.file;
    _b
      ..writeln('### <!--[src_$n]--> ${cs.path}')
      ..writeln()
      ..writeln('- **Locus:** ${file.locus.name}');
    if (file.units.isNotEmpty) {
      _b.writeln('- **Units:** ${file.units.map(_code).join(', ')}');
    }
    if (cs.imports.isNotEmpty) {
      _b.writeln('- **Imports:** ${cs.imports.map(_code).join(', ')}');
    }
    if (cs.exports.isNotEmpty) {
      _b.writeln('- **Exports:** ${cs.exports.map(_code).join(', ')}');
    }
    _b.writeln();
    final steps = {for (final s in file.steps) '${s.owner}#${s.body}': s};
    var declNumber = 0;
    for (final entry in index.topLevel.where((e) => e.file == file)) {
      declNumber++;
      final id = 'decl_${n}_$declNumber';
      final members = index.membersOf(entry);
      _declaration(
        entry.declaration,
        id,
        '####',
        steps,
        bodiesOfMembers: {for (final m in members) m.name},
      );
      var memberNumber = 0;
      for (final member in members) {
        memberNumber++;
        _declaration(
          member,
          'member_${n}_${declNumber}_$memberNumber',
          '#####',
          steps,
          owner: entry.declaration.name,
        );
      }
    }
  }

  void _declaration(
    CsDeclaration d,
    String id,
    String level,
    Map<String, IrBodySteps> steps, {
    String? owner,
    Set<String> bodiesOfMembers = const {},
  }) {
    _b
      ..writeln('$level <!--[$id]--> ${d.kind.name} ${_code(d.name)}')
      ..writeln();
    final modifiers = [
      if (d.isAbstract) 'abstract',
      if (d.isStatic) 'static',
      if (d.isConst) 'const',
      if (d.isFinal) 'final',
      if (d.isLate) 'late',
    ];
    if (modifiers.isNotEmpty) {
      _b.writeln('- **Modifiers:** ${modifiers.join(', ')}');
    }
    if (d.declaredType != null) {
      _b.writeln('- **Type:** ${_code(d.declaredType!)}');
    }
    if (d.typeParameters != null) {
      _b.writeln('- **Type parameters:** ${_code(d.typeParameters!)}');
    }
    if (d.superclass != null) {
      _b.writeln('- **Extends:** ${_code(d.superclass!)}');
    }
    if (d.interfaces.isNotEmpty) {
      _b.writeln('- **Implements:** ${d.interfaces.map(_code).join(', ')}');
    }
    if (d.mixins.isNotEmpty) {
      _b.writeln('- **With:** ${d.mixins.map(_code).join(', ')}');
    }
    if (d.initialiser != null) {
      _b.writeln('- **Initialiser:** ${_code(d.initialiser!)}');
    }
    final link = d.codeSpec;
    if (link != null) {
      _b.writeln(
        '- **CodeSpec:** ${_code(link.id)}'
        '${link.source.isEmpty ? '' : ', source: ${link.source.map(_code).join(', ')}'}',
      );
    }
    if (d.markers.isNotEmpty) {
      _b.writeln('- **Markers:**');
      for (final m in d.markers) {
        _b.writeln('  - ${_code(_marker(m))}');
      }
    }
    final annotations = [
      for (final a in d.annotations)
        if (!d.markers.any((m) => a.source.startsWith('@${m.name}')) &&
            !a.source.startsWith('@CodeSpec(') &&
            !a.source.startsWith('@DocSpec('))
          a.source,
    ];
    if (annotations.isNotEmpty) {
      _b.writeln('- **Annotations:**');
      for (final a in annotations) {
        _b.writeln('  - ${_code(a.replaceAll(RegExp(r'\s+'), ' '))}');
      }
    }
    final refs = d.docSpec ?? const <CsDocRef>[];
    if (refs.isNotEmpty) {
      _b.writeln('- **Back-links:**');
      for (final r in refs) {
        final token = specRendition == null
            ? _code(r.sectionId)
            : '[${_code(r.sectionId)}](${p.posix.joinAll(p.split(specRendition!))}#${r.sectionId})';
        _b.writeln('  - $token: ${r.description}');
      }
    }
    final doc = d.docComment;
    if (doc != null) {
      _b.writeln();
      for (final line in doc.lines) {
        final text = line.trimLeft().replaceFirst(RegExp(r'^/// ?'), '');
        _b.writeln(text.isEmpty ? '>' : '> $text');
      }
    }
    _b.writeln();
    // A body is shown once, under the member that has it; a top-level
    // declaration shows only the bodies no member of it claims.
    for (final body in d.bodies) {
      if (bodiesOfMembers.contains(body.name)) continue;
      _body(d, body, steps, owner: owner);
    }
  }

  void _body(
    CsDeclaration declaration,
    CsMethodBody body,
    Map<String, IrBodySteps> steps, {
    String? owner,
  }) {
    final params = [
      for (final param in body.parameters)
        '${param.type ?? 'dynamic'} ${param.name}',
    ].join(', ');
    _b.writeln(
      '- **Body** ${_code(body.name)}: ${body.shape.name}'
      '${body.returnType == null ? '' : ', returns ${_code(body.returnType!)}'}'
      '${params.isEmpty ? '' : ', parameters ${_code(params)}'}'
      '${body.isAsync ? ', async' : ''}',
    );
    if (body.thrownType != null || body.thrownMessage != null) {
      _b.writeln(
        '  - throws ${_code(body.thrownType ?? '')}'
        '${body.thrownMessage == null ? '' : ': ${body.thrownMessage}'}',
      );
    }
    final record = steps['${owner ?? declaration.name}#${body.name}'];
    if (record != null) {
      _b
        ..writeln()
        ..writeln('```text');
      if (record.steps != null) {
        _steps(record.steps!, '');
      } else {
        _b.writeln('no steps: ${record.issue}');
      }
      _b.writeln('```');
    }
    _b.writeln();
  }

  void _steps(List<IrStep> steps, String indent) {
    for (final s in steps) {
      switch (s) {
        case IrCallStep(:final method, :final arguments):
          _b.writeln('${indent}call $method(${arguments.join(', ')})');
        case IrReturnStep(:final method, :final arguments):
          _b.writeln(
            method == null
                ? '${indent}return'
                : '${indent}return $method(${arguments.join(', ')})',
          );
        case IrGuardedStep(:final guard, :final arguments, :final steps):
          _b.writeln('${indent}when $guard(${arguments.join(', ')}):');
          _steps(steps, '$indent  ');
      }
    }
  }

  static String _marker(CsMarker m) {
    final args = [
      ...m.positional.map((v) => '$v'),
      ...m.named.entries.map((e) => '${e.key}: ${e.value}'),
    ];
    return '@${m.name}${args.isEmpty ? '' : '(${args.join(', ')})'}';
  }
}
