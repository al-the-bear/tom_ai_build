String? _router(
  Map<String, dynamic> openApi,
  List<({String area, IrFile file})> server,
  _Symbols symbols,
  String module,
) {
  // The service unit holding each operation's handler (CE-SU), and the
  // handler's body.
  final handlers =
      <String, ({String owner, String method, CsMethodBody body})>{};
  for (final f in server) {
    final index = irFileIndex(f.area, f.file);
    for (final e in index.topLevel) {
      if (irMarker(e.declaration, 'CsServiceUnit') == null) continue;
      for (final m in index.membersOf(e)) {
        final op = irString(irMarker(m, 'CsEndpoint')?.positional.firstOrNull);
        final b = m.bodies.where((b) => b.name == m.name).firstOrNull;
        if (op != null && b != null) {
          handlers[op] = (owner: e.declaration.name, method: m.name, body: b);
        }
      }
    }
  }
  final imports = <String>{
    'encoding/json',
    'net/http',
    'github.com/go-chi/chi/v5',
  };
  final types = _Types(symbols, _server, module, const {}, imports);
  final services = <String>{};
  final routes = <String>[];
  for (final o in openApiOperations(openApi)) {
    final h = handlers[o.op];
    if (h == null) continue;
    services.add(h.owner);
    final params = h.body.parameters;
    if (params.length > 1) {
      throw IrMapException(
        '${h.owner}.${h.method}: a handler takes at most its request',
      );
    }
    final call =
        'services.${h.owner}.${_exported(h.method)}(${['req.Context()', if (params.isNotEmpty) 'request'].join(', ')})';
    final returnsValue = types.resultOf(h.body.returnType) != null;
    routes.addAll([
      '\tr.Post(${jsonEncode(o.path)}, func(w http.ResponseWriter, req *http.Request) {',
      if (params.isNotEmpty) ...[
        '\t\tvar request ${types.of(params.single.type ?? 'Object')}',
        '\t\tif err := json.NewDecoder(req.Body).Decode(&request); err != nil {',
        '\t\t\thttp.Error(w, err.Error(), http.StatusInternalServerError)',
        '\t\t\treturn',
        '\t\t}',
      ],
      if (returnsValue) ...[
        '\t\tanswer, err := $call',
        '\t\trespond(w, answer, err)',
      ] else ...[
        '\t\trespond(w, nil, $call)',
      ],
      '\t})',
    ]);
  }
  if (services.isEmpty) return null;
  final sorted = services.toList()..sort();
  return [
    '// $_generated',
    '',
    'package $_server',
    ..._importBlock(imports, module),
    '',
    '// Services are the service units the routes call, one each.',
    'type Services struct {',
    for (final (i, s) in sorted.indexed) ...[if (i > 0) '', '\t$s $s'],
    '}',
    '',
    '// NewRouter returns the chi router of the operations: every operation a',
    '// POST of its request to its service unit\'s handler, its answer the',
    '// Result envelope. A handler\'s error and a body that does not decode are',
    '// transport errors, the only 5xx (codespecs_mapping.md §7).',
    'func NewRouter(services Services) http.Handler {',
    '\tr := chi.NewRouter()',
    ...routes,
    '\treturn r',
    '}',
    '',
    'func respond(w http.ResponseWriter, answer any, err error) {',
    '\tif err != nil {',
    '\t\thttp.Error(w, err.Error(), http.StatusInternalServerError)',
    '\t\treturn',
    '\t}',
    '\tbody, err := json.Marshal(answer)',
    '\tif err != nil {',
    '\t\thttp.Error(w, err.Error(), http.StatusInternalServerError)',
    '\t\treturn',
    '\t}',
    '\tw.Header().Set("Content-Type", "application/json")',
    '\t_, _ = w.Write(body)',
    '}',
    '',
  ].join('\n');
}

