/// Registry-driven test generation (`tom_specs_project_flow.md`, Phase 5).
///
/// From a specification's registries ([RegistrySet]) this writes committed
/// Dart test files into an application's test folder: one suite for the
/// operations (a permitted and a refused case per role of the role catalogue,
/// a case per custom authorization handler, per declared error code, and per
/// stated idempotency, audit event and rate-limit class) and one for the
/// screens (each screen rendered as each role, and every screen operation a
/// role would be refused hidden from it). The tests call an application-owned
/// [harnessInterface] — the generator knows the registries, the application
/// knows how to call an operation or render a screen as a principal.
///
/// Generation also cross-checks the registries in both directions and returns
/// the inconsistencies as [RegistryFinding]s: an error code an operation names
/// that the error-code registry does not declare, a role a requirement names
/// that the role catalogue does not, a screen calling an operation the
/// operation registry does not hold, and an operation a person calls that no
/// screen calls.
///
/// [checkRegistryTests] compares generated files on disk with what the
/// registries give now, so a hand-removed case or a stale suite is reported.
library;

import 'registries.dart';

/// The header every generated file starts with.
const registryTestsHeader =
    '// GENERATED by tom_specs_clitool generate_registry_tests — do not edit.\n'
    '// Re-run the generator after a registry change; '
    '`--check` reports a stale suite.\n';

/// The file name of the generated harness interface.
const harnessFile = 'registry_harness.g.dart';

/// The file name of the generated operations suite.
const operationsFile = 'registry_operations_test.dart';

/// The file name of the generated screens suite.
const screensFile = 'registry_screens_test.dart';

/// One inconsistency between the registries, or between generated files and
/// the registries.
class RegistryFinding {
  /// A stable code: `undeclaredErrorCode`, `unknownRole`, `unknownOperation`,
  /// `operationWithoutScreen`, `missingFile`, `missingCase`, `extraCase`,
  /// `staleFile`.
  final String code;

  /// What is wrong, naming the registry entries.
  final String message;

  /// Creates a finding.
  const RegistryFinding(this.code, this.message);

  @override
  String toString() => '[$code] $message';
}

/// The generated files and the registry findings of one generation.
class RegistryTestGeneration {
  /// File name → content.
  final Map<String, String> files;

  /// The cross-check findings over the registries.
  final List<RegistryFinding> findings;

  /// Creates a generation.
  const RegistryTestGeneration(this.files, this.findings);
}

/// The interface the generated tests call; the application implements it in
/// its own `registry_harness.dart` and exposes `createRegistryTestHarness()`.
const harnessInterface = '''
/// What the generated registry tests need from the application: calling an
/// operation and rendering a screen as a test principal. A null [role] is the
/// anonymous principal.
abstract class RegistryTestHarness {
  /// The operation is accepted for the principal.
  Future<void> expectPermitted(String operation, {String? role});

  /// The operation is refused for the principal.
  Future<void> expectRefused(String operation, {String? role});

  /// The operation's access is decided by the registered [handler].
  Future<void> expectHandlerDecides(String operation, String handler);

  /// The operation can answer the error [code].
  Future<void> expectErrorCode(String operation, String code);

  /// Repeating the operation repeats no effect (with the same idempotency key
  /// when [withKey]).
  Future<void> expectIdempotent(String operation, {required bool withKey});

  /// The operation records the audit [event].
  Future<void> expectAuditEvent(String operation, String event);

  /// The operation is throttled by the rate-limit class [rateClass].
  Future<void> expectRateLimitClass(String operation, String rateClass);

  /// The screen renders for the principal without a hard-coded label.
  Future<void> expectScreenRenders(String screen, {String? role});

  /// The screen shows no action for [operation] to the principal.
  Future<void> expectActionHidden(String screen, String operation, {String? role});
}
''';

/// Whether [role] satisfies [requirement], or null when the registries cannot
/// decide (a custom handler, a graded or resource-key requirement, none).
bool? permits(RegistryRequirement requirement, RegistryRole? role) {
  switch (requirement.kind) {
    case 'public':
      return true;
    case 'authenticated':
      return role != null;
    case 'denied':
      return false;
    case 'role':
      return role != null && requirement.roles.contains(role.name);
    case 'entitlement':
      if (role == null) return false;
      // A role may hold a pattern (`app.*`) and a requirement may name one;
      // either side matching the other grants access.
      return role.entitlements.any(
        (e) => requirement.patterns.any((p) => _glob(p, e) || _glob(e, p)),
      );
    default:
      return null;
  }
}

bool _glob(String pattern, String value) {
  final re = RegExp('^${pattern.split('*').map(RegExp.escape).join('.*')}\$');
  return re.hasMatch(value);
}

String _q(String s) => "'${s.replaceAll(r'\', r'\\').replaceAll("'", r"\'")}'";

/// Generates the test files for [registries]; [harnessImport] is the import
/// URI of the application's harness (default `registry_harness.dart`, beside
/// the generated files).
RegistryTestGeneration generateRegistryTests(
  RegistrySet registries, {
  String harnessImport = 'registry_harness.dart',
}) {
  final findings = <RegistryFinding>[];
  final declaredCodes = registries.errorCodes.toSet();
  final operationNames = {for (final o in registries.operations) o.name};
  final roleNames = {for (final r in registries.roles) r.name};
  final calledFromScreens = <String>{};

  // Cross-checks.
  for (final op in registries.operations) {
    for (final code in op.errorCodes) {
      if (!declaredCodes.contains(code)) {
        findings.add(
          RegistryFinding(
            'undeclaredErrorCode',
            'operation ${op.name} names error code $code, which the '
                'error-code registry does not declare',
          ),
        );
      }
    }
    for (final role in op.requirement.roles) {
      if (!roleNames.contains(role)) {
        findings.add(
          RegistryFinding(
            'unknownRole',
            'operation ${op.name} requires role $role, which the role '
                'catalogue does not declare',
          ),
        );
      }
    }
  }
  for (final screen in registries.screens) {
    for (final op in screen.operations) {
      calledFromScreens.add(op);
      if (!operationNames.contains(op)) {
        findings.add(
          RegistryFinding(
            'unknownOperation',
            'screen ${screen.id} calls operation $op, which the operation '
                'registry does not hold',
          ),
        );
      }
    }
  }
  for (final op in registries.operations) {
    if (op.personCalled && !calledFromScreens.contains(op.name)) {
      findings.add(
        RegistryFinding(
          'operationWithoutScreen',
          'operation ${op.name} is called by a person '
              '(${op.requirement.kind} requirement) but no screen calls it',
        ),
      );
    }
  }

  // Operations suite.
  final ops = StringBuffer()
    ..write(registryTestsHeader)
    ..writeln()
    ..writeln("import 'package:test/test.dart';")
    ..writeln()
    ..writeln("import ${_q(harnessImport)};")
    ..writeln("import '$harnessFile';")
    ..writeln()
    ..writeln('void main() {')
    ..writeln(
      '  late final RegistryTestHarness harness = createRegistryTestHarness();',
    );
  for (final op in registries.operations) {
    ops.writeln();
    ops.writeln('  group(${_q('operation ${op.name}')}, () {');
    final principals = <RegistryRole?>[null, ...registries.roles];
    for (final role in principals) {
      final who = role?.name ?? 'anonymous';
      final permitted = permits(op.requirement, role);
      if (permitted == null) continue;
      final roleArg = role == null ? '' : ', role: ${_q(role.name)}';
      final verb = permitted ? 'expectPermitted' : 'expectRefused';
      ops.writeln(
        '    test(${_q('OPS-${op.name}-$who: ${permitted ? 'permitted' : 'refused'}')}, '
        '() => harness.$verb(${_q(op.name)}$roleArg));',
      );
    }
    if (op.requirement.kind == 'custom' && op.requirement.handler.isNotEmpty) {
      ops.writeln(
        '    test(${_q('OPS-${op.name}-handler: decided by ${op.requirement.handler}')}, '
        '() => harness.expectHandlerDecides(${_q(op.name)}, '
        '${_q(op.requirement.handler)}));',
      );
    }
    for (final code in op.errorCodes) {
      ops.writeln(
        '    test(${_q('OPS-${op.name}-error-$code: can answer $code')}, '
        '() => harness.expectErrorCode(${_q(op.name)}, ${_q(code)}));',
      );
    }
    if (op.idempotency == 'idempotent' ||
        op.idempotency == 'idempotentWithKey') {
      final withKey = op.idempotency == 'idempotentWithKey';
      ops.writeln(
        '    test(${_q('OPS-${op.name}-idempotent: a repeat has no further effect')}, '
        '() => harness.expectIdempotent(${_q(op.name)}, withKey: $withKey));',
      );
    }
    if (op.auditEvent.isNotEmpty) {
      ops.writeln(
        '    test(${_q('OPS-${op.name}-audit: records ${op.auditEvent}')}, '
        '() => harness.expectAuditEvent(${_q(op.name)}, ${_q(op.auditEvent)}));',
      );
    }
    if (op.rateLimitClass.isNotEmpty) {
      ops.writeln(
        '    test(${_q('OPS-${op.name}-rate: throttled as ${op.rateLimitClass}')}, '
        '() => harness.expectRateLimitClass(${_q(op.name)}, '
        '${_q(op.rateLimitClass)}));',
      );
    }
    ops.writeln('  });');
  }
  ops.writeln('}');

  // Screens suite: the render matrix and the hidden actions.
  final byName = {for (final o in registries.operations) o.name: o};
  final scr = StringBuffer()
    ..write(registryTestsHeader)
    ..writeln()
    ..writeln("import 'package:test/test.dart';")
    ..writeln()
    ..writeln("import ${_q(harnessImport)};")
    ..writeln("import '$harnessFile';")
    ..writeln()
    ..writeln('void main() {')
    ..writeln(
      '  late final RegistryTestHarness harness = createRegistryTestHarness();',
    );
  for (final screen in registries.screens) {
    scr.writeln();
    scr.writeln('  group(${_q('screen ${screen.id}')}, () {');
    for (final role in registries.roles) {
      scr.writeln(
        '    test(${_q('SCR-${screen.id}-${role.name}: renders')}, '
        '() => harness.expectScreenRenders(${_q(screen.id)}, '
        'role: ${_q(role.name)}));',
      );
      for (final opName in screen.operations) {
        final op = byName[opName];
        if (op == null) continue;
        if (permits(op.requirement, role) == false) {
          scr.writeln(
            '    test(${_q('SCR-${screen.id}-${role.name}-hides-$opName: action hidden')}, '
            '() => harness.expectActionHidden(${_q(screen.id)}, ${_q(opName)}, '
            'role: ${_q(role.name)}));',
          );
        }
      }
    }
    scr.writeln('  });');
  }
  scr.writeln('}');

  return RegistryTestGeneration({
    harnessFile: '$registryTestsHeader\n$harnessInterface',
    operationsFile: ops.toString(),
    screensFile: scr.toString(),
  }, findings);
}

/// The test ids (`OPS-…`, `SCR-…`) a generated file declares.
Set<String> registryTestIds(String content) => {
  for (final m in RegExp(
    r"test\(\s*'((?:OPS|SCR)-[^:']+):",
  ).allMatches(content))
    m.group(1)!,
};

/// Compares the files on disk ([existing], file name → content, absent when
/// missing) with [generation]: a missing file, every case the registries
/// give that a file lacks (a removed case), every case a file holds that the
/// registries no longer give, and any other difference as a stale file.
List<RegistryFinding> checkRegistryTests(
  RegistryTestGeneration generation,
  Map<String, String?> existing,
) {
  final out = <RegistryFinding>[];
  for (final MapEntry(key: name, value: want) in generation.files.entries) {
    final have = existing[name];
    if (have == null) {
      out.add(RegistryFinding('missingFile', '$name is not generated yet'));
      continue;
    }
    // Formatting is not a registry change: the CLI runs `dart format` over
    // what it writes, so content is compared with whitespace removed.
    // The formatter also adds trailing commas when it splits a list.
    String squash(String v) => v
        .replaceAll(RegExp(r'\s+'), '')
        .replaceAll(',)', ')')
        .replaceAll(',]', ']')
        .replaceAll(',}', '}');
    if (squash(have) == squash(want)) continue;
    final wantIds = registryTestIds(want);
    final haveIds = registryTestIds(have);
    final missing = wantIds.difference(haveIds).toList()..sort();
    final extra = haveIds.difference(wantIds).toList()..sort();
    for (final id in missing) {
      out.add(RegistryFinding('missingCase', '$name lacks case $id'));
    }
    for (final id in extra) {
      out.add(
        RegistryFinding(
          'extraCase',
          '$name holds case $id, which the registries no longer give',
        ),
      );
    }
    if (missing.isEmpty && extra.isEmpty) {
      out.add(
        RegistryFinding(
          'staleFile',
          '$name differs from what the registries give — regenerate it',
        ),
      );
    }
  }
  return out;
}
