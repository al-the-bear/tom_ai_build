/// Consolidated DocSpecs parsing + validation (DR1 §6): the embedded,
/// runtime-owned equivalent of the `tom_doc_scanner` + `tom_doc_specs` split,
/// redesigned as one coherent API. This is the reference implementation the
/// other eight language runtimes port; the Dart violation messages are the
/// golden reference — every port must produce the same `rule` / `sectionId` /
/// `line` triples.
///
/// Three capabilities, one module:
///
///  1. **Parse** — [DocSpecsDocument.parse] reads any DocSpecs `*.md`
///     *schema-free* into a generic section tree ([DocSpecsSection]): ids,
///     titles, heading levels, body text, source lines. Fenced code blocks
///     shield their lines from heading detection ([MarkdownFenceTracker], the
///     exact semantics of the [SpecDocumentMarkdown] codec).
///  2. **Validate** — [DocSpecsValidator.validate] checks a parsed document
///     against a [DocSpecsSchema] (a `*.docspecs-schema.yaml` as generated by
///     the DR3 schema generator) and returns a structured
///     [DocSpecsViolation] list. Validation **never fails fast** — the full
///     list is always produced; a document is valid iff the list is empty.
///  3. **Bind** — [bindDocSpecsMarkdown] maps the same markdown onto the SOM
///     metadata tree, delegating to [SpecDocumentMarkdown.parse] (DR1 §1.7).
///
/// Supported schema features (the DR1 §6 scope): section-types (`prefix`,
/// `pattern-check-id`, `subsection-types` with `min-count`/`max-count`,
/// `format`, `text-required`, `min-text-length`/`max-text-length`,
/// `description`), form-types (fields with `required` and `pattern-check`),
/// and the `document:` structure (top-level sections, `optional`).
/// `validation-prompt` values are carried as data. Anything else — generator
/// placeholders, database-schema sections, custom tags — is **ignored on
/// load** and named in [DocSpecsSchema.warnings]; nothing is silently
/// dropped (DR1 §7).
library;

import 'package:yaml/yaml.dart';

import 'spec_document.dart';
import 'spec_document_markdown.dart';
import 'spec_model.dart';

/// The DR1 §6 violation rule vocabulary — identical across all nine runtimes.
enum DocSpecsViolationRule {
  /// A heading's id resolves to no section-type, or to a type not allowed at
  /// its nesting position.
  unknownSection,

  /// A required section (document slot or `min-count >= 1` subsection) has no
  /// occurrence.
  missingRequiredSection,

  /// A section id fails its type's `pattern-check-id`.
  idPatternMismatch,

  /// A subsection occurs, but fewer times than its `min-count`.
  tooFewItems,

  /// A subsection occurs more times than its numeric `max-count`.
  tooManyItems,

  /// A `required` form field is absent (or empty) in a form-formatted section.
  missingRequiredField,

  /// A form field value fails its `pattern-check`.
  fieldPatternMismatch,

  /// A `text-required` section has no body text.
  textRequired,

  /// A section's body text length is outside `min-text-length` /
  /// `max-text-length`.
  textLengthOut,

  /// The document/root shape does not match — wrong root id vs `title-format`,
  /// or a non-form `format` section without the demanded fenced block.
  formatMismatch,

  /// A heading line without a parseable `<!--[SECTION-ID]-->` comment.
  malformedHeading,
}

/// One structured violation (DR1 §6): the [rule], the offending [sectionId]
/// (when one exists), the bound runtime [path] (when resolvable), the 1-based
/// source [line], and a human-readable [message].
class DocSpecsViolation {
  DocSpecsViolation({
    required this.rule,
    required this.line,
    required this.message,
    this.sectionId,
    this.path,
  });

  final DocSpecsViolationRule rule;
  final String? sectionId;
  final String? path;
  final int line;
  final String message;

  @override
  String toString() =>
      'line $line: ${rule.name}${sectionId != null ? ' [$sectionId]' : ''}'
      '${path != null ? ' ($path)' : ''} — $message';
}

// ---------------------------------------------------------------------------
// 1. Generic (schema-free) markdown parse
// ---------------------------------------------------------------------------

/// One section of a schema-free DocSpecs parse: its [id] (null for a
/// malformed heading), heading [title], markdown [level], 1-based heading
/// [line], accumulated [bodyLines] (each with its own source line =
/// [bodyStartLine] + index), and nested [children].
class DocSpecsSection {
  DocSpecsSection({
    required this.id,
    required this.title,
    required this.level,
    required this.line,
  });

  final String? id;
  final String title;
  final int level;
  final int line;

  /// The raw body lines directly under this heading (before any child
  /// heading), in source order.
  final List<String> bodyLines = [];

  /// The source line of the first body line (heading line + 1).
  int get bodyStartLine => line + 1;

  final List<DocSpecsSection> children = [];

  /// The trimmed body text (leading/trailing blank lines removed).
  String get text {
    var start = 0;
    var end = bodyLines.length;
    while (start < end && bodyLines[start].trim().isEmpty) {
      start++;
    }
    while (end > start && bodyLines[end - 1].trim().isEmpty) {
      end--;
    }
    return bodyLines.sublist(start, end).join('\n');
  }
}

/// A schema-free DocSpecs markdown parse: the declared schema header (if
/// any), the top-level [sections], and the parse-time [violations]
/// (malformed headings). Validation against a schema is a separate step —
/// [DocSpecsValidator.validate] — which folds these violations into its
/// result.
class DocSpecsDocument {
  DocSpecsDocument._();

  /// The `<!-- docspec: schema-id/version -->` declaration, when present.
  String? declaredSchema;

  /// Top-level (usually one: the document root) sections in source order.
  final List<DocSpecsSection> sections = [];

  /// Parse-time violations: [DocSpecsViolationRule.malformedHeading] for each
  /// heading without a `<!--[SECTION-ID]-->` comment.
  final List<DocSpecsViolation> violations = [];

  static final RegExp _docspecHeader =
      RegExp(r'^<!--\s*docspec:\s*(\S+)\s*-->\s*$');

  /// Parses [text] into the generic section tree. Any markdown is accepted;
  /// structural problems surface as [violations], never as exceptions.
  static DocSpecsDocument parse(String text) {
    final doc = DocSpecsDocument._();
    final fence = MarkdownFenceTracker();
    final stack = <DocSpecsSection>[];
    final lines = text.split('\n');
    for (var i = 0; i < lines.length; i++) {
      final raw = lines[i];
      final lineNo = i + 1;
      final trimmed = raw.trimRight();
      if (!fence.inFence) {
        if (stack.isEmpty && doc.declaredSchema == null) {
          final d = _docspecHeader.firstMatch(trimmed);
          if (d != null) {
            doc.declaredSchema = d.group(1);
            continue;
          }
        }
        final h = SpecDocumentMarkdown.headingLine.firstMatch(trimmed);
        if (h != null) {
          final level = h.group(1)!.length;
          final rest = h.group(2)!.trim();
          final c = SpecDocumentMarkdown.headlineComment.firstMatch(rest);
          final section = DocSpecsSection(
            id: c?.group(1),
            title: c != null ? c.group(2)!.trim() : rest,
            level: level,
            line: lineNo,
          );
          if (c == null) {
            doc.violations.add(DocSpecsViolation(
              rule: DocSpecsViolationRule.malformedHeading,
              line: lineNo,
              message: 'heading "$rest" carries no <!--[SECTION-ID]--> '
                  'headline comment',
            ));
          }
          while (stack.isNotEmpty && stack.last.level >= level) {
            stack.removeLast();
          }
          (stack.isEmpty ? doc.sections : stack.last.children).add(section);
          stack.add(section);
          continue;
        }
      }
      if (stack.isNotEmpty) stack.last.bodyLines.add(raw);
      fence.feed(raw);
    }
    return doc;
  }
}

