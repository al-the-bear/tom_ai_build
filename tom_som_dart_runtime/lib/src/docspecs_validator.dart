// 4. Binding onto the SOM metadata tree (DR1 §6 capability 3)
// ---------------------------------------------------------------------------

/// Binds a DocSpecs markdown [text] onto the SOM metadata tree of [model],
/// staging values against [document]'s path grammar — the §1.7 entry point,
/// delegated to [SpecDocumentMarkdown.parse].
SpecMarkdownResult bindDocSpecsMarkdown(
        SpecModel model, SpecDocument document, String text) =>
    SpecDocumentMarkdown(model, document).parse(text);
