const String _shared = 'shared';
const String _server = 'server';
const String _tom = 'tom';

/// The files of the Go module [share]'s server is written as — `<path>` →
/// text, under the module's directory, which is the server package's name.
/// [all] is the whole IR folder the share was taken from: the module carries
/// the shared locus as its `shared` package, and the routes come from the
/// OpenAPI document of the whole folder (`irspecs_ir.md` §10).
Map<String, String> mapGoServer(
  List<IrDocument> share, {
  List<IrDocument>? all,
}) {
  final everything = all ?? share;
  final module =
      _packageName(share, CsLocus.server) ??
      _packageName(everything, CsLocus.server);
  if (module == null) return const {};
  final server = [
    for (final d in share)
      if (d.area != kIrPackageArea)
        for (final f in d.files)
          if (f.locus == CsLocus.server) (area: d.area, file: f),
  ];
  final shared = [
    for (final d in everything)
      if (d.area != kIrPackageArea)
        for (final f in d.files)
          if (f.locus == CsLocus.shared) (area: d.area, file: f),
  ];
  final symbols = _Symbols([
    for (final s in shared) (package: _shared, area: s.area, file: s.file),
    for (final s in server) (package: _server, area: s.area, file: s.file),
  ]);

  final out = <String, String>{};
  final names = <String>{};
  for (final (package, files) in [(_shared, shared), (_server, server)]) {
    for (final f in files) {
      final name = _fileName(f.file.file.path, names);
      out['$module/$package/$name'] = _FileWriter(
        file: f.file,
        area: f.area,
        package: package,
        module: module,
        symbols: symbols,
      ).render();
    }
  }
  out['$module/$_tom/tom.go'] = _tomPackage();

  final openApi =
      jsonDecode(emitOpenApi(everything).files[kOpenApiFile]!)
          as Map<String, dynamic>;
  final router = _router(openApi, server, symbols, module);
  if (router != null) out['$module/$_server/router.go'] = router;

  final tables = _tables(server, symbols);
  if (tables.isNotEmpty) {
    out['$module/sqlc.yaml'] = _sqlcYaml(tables);
    out['$module/db/schema.sql'] = _schemaSql(tables);
    for (final t in tables) {
      out['$module/db/query/${t.table}.sql'] = _querySql(t);
    }
  }

  out['$module/go.mod'] = [
    '// $_generated',
    '',
    'module $module',
    '',
    'go $kGoLanguageVersion',
    if (router != null) ...[
      '',
      for (final MapEntry(:key, :value) in kGoDependencyVersions.entries)
        'require $key $value',
    ],
    '',
  ].join('\n');
  if (router != null) out['$module/go.sum'] = '${_goSum.join('\n')}\n';
  return out;
}

const String _generated =
    'Code generated by TomSpecs Phase 4 (CodeSpecs, mapper go-server). '
    'DO NOT EDIT.';

String? _packageName(List<IrDocument> documents, CsLocus locus) {
  for (final d in documents) {
    for (final p in d.projects) {
      if (p.locus == locus) return p.packageName;
    }
  }
  return null;
}

/// The GOOS and GOARCH values and `test`: a file whose name ends in
/// `_<one of them>` is a build-constrained or test file to `go build`.
const Set<String> _reservedSuffixes = {
  'aix', 'android', 'darwin', 'dragonfly', 'freebsd', 'hurd', 'illumos', //
  'ios', 'js', 'linux', 'nacl', 'netbsd', 'openbsd', 'plan9', 'solaris',
  'wasip1', 'windows', 'zos', '386', 'amd64', 'arm', 'arm64', 'loong64',
  'mips', 'mipsle', 'mips64', 'mips64le', 'ppc64', 'ppc64le', 'riscv64',
  's390x', 'wasm', 'test',
};

/// `lib/src/data_access/order.dart` → `data_access_order.go`; a name Go would
/// read as build-constrained (`…_linux`, `…_test`) gets `_gen`, a name already
/// taken a number.
String _fileName(String dartPath, Set<String> taken) {
  var path = dartPath;
  if (path.startsWith('lib/')) path = path.substring(4);
  if (path.startsWith('src/')) path = path.substring(4);
  if (path.endsWith('.dart')) path = path.substring(0, path.length - 5);
  var stem = path.replaceAll('/', '_');
  if (_reservedSuffixes.contains(stem.split('_').last)) stem = '${stem}_gen';
  var name = stem;
  for (var i = 2; !taken.add(name); i++) {
    name = '${stem}_$i';
  }
  return '$name.go';
}

String _exported(String name) =>
    name.isEmpty ? name : '${name[0].toUpperCase()}${name.substring(1)}';

/// Go's keywords and predeclared names a Dart parameter could collide with.
const Set<String> _goReserved = {
  'break', 'case', 'chan', 'const', 'continue', 'default', 'defer', 'else', //
  'fallthrough', 'for', 'func', 'go', 'goto', 'if', 'import', 'interface',
  'map', 'package', 'range', 'return', 'select', 'struct', 'switch', 'type',
  'var', 'ctx', 'err', 'zero', 'shared', 'tom', 'time', 'context',
};

String _local(String name) => _goReserved.contains(name) ? '${name}_' : name;

