/// `{T}` → `[T any]`.
String _goTypeParameters(Set<String> names) =>
    names.isEmpty ? '' : '[${names.map((n) => '$n any').join(', ')}]';

/// The Go form of a Dart type, as written in [package]; [imports] collects
/// the packages it needs. Types follow `irspecs_ir.md` §10.1's JSON Schema
/// mapping, so the wire types and the schemas agree.
class _Types {
  final _Symbols symbols;
  final String package;
  final String module;
  final Set<String> typeParameters;
  final Set<String> imports;

  _Types(
    this.symbols,
    this.package,
    this.module,
    this.typeParameters,
    this.imports,
  );

  _Types withParameters(Set<String> more) =>
      _Types(symbols, package, module, {...typeParameters, ...more}, imports);

  /// Whether a Go type is already nil-able (no pointer for a nullable one).
  static bool _nilable(String go) =>
      go.startsWith('[]') ||
      go.startsWith('map[') ||
      go == 'any' ||
      go.startsWith('*');

  String of(String dart) {
    var t = dart.trim();
    if (t.endsWith('?')) {
      final inner = of(t.substring(0, t.length - 1));
      return _nilable(inner) ? inner : '*$inner';
    }
    final generic = RegExp(r'^(\w+)<(.*)>$').firstMatch(t);
    if (generic != null) {
      final base = generic.group(1)!;
      final args = irSplitTypeArguments(generic.group(2)!);
      switch (base) {
        case 'List' || 'Iterable' || 'Set':
          return '[]${of(args.single)}';
        case 'Map':
          return 'map[${of(args[0])}]${of(args[1])}';
        case 'Future':
          throw IrMapException('`$t` is a Future outside a method result');
        case 'TomRepository':
          imports.add('$module/$_tom');
          return 'tom.Repository[${args.map(of).join(', ')}]';
      }
      return '${_named(base)}[${args.map(of).join(', ')}]';
    }
    switch (t) {
      case 'String' || 'Uri' || 'Duration':
        return 'string';
      case 'DateTime':
        imports.add('time');
        return 'time.Time';
      case 'int':
        return 'int';
      case 'double' || 'num':
        return 'float64';
      case 'bool':
        return 'bool';
      case 'Object' || 'dynamic':
        return 'any';
    }
    if (typeParameters.contains(t)) return t;
    if (t.startsWith('Cs') &&
        (t.endsWith('Ref') || t.endsWith('Key') || t.endsWith('Code'))) {
      return 'string';
    }
    return _named(t);
  }

  String _named(String name) {
    final s = symbols.byName[name];
    if (s == null) {
      throw IrMapException('the type `$name` has no Go form');
    }
    if (s.package == package) return name;
    imports.add('$module/${s.package}');
    return '${s.package}.$name';
  }

  /// A method's results: `Future<X>` and `X` → `(X, error)`; `void` and
  /// `Future<void>` → `error`. Returns the value type, or `null` for none.
  String? resultOf(String? dart) {
    var t = (dart ?? 'void').trim();
    final future = RegExp(r'^(?:Future|FutureOr)<(.*)>$').firstMatch(t);
    if (future != null) t = future.group(1)!.trim();
    if (t == 'void' || t == 'Future') return null;
    return of(t);
  }
}

String _results(String? value) => value == null ? 'error' : '($value, error)';

