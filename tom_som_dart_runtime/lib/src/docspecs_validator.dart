// 2. Schema loading
// ---------------------------------------------------------------------------

/// The DocSpecs id transform used for prefix matching: every run of
/// non-alphanumeric characters becomes `_` — the exact transform the DR3
/// generator applies when deriving a `prefix:` from a section id (the
/// DocSpecs prefix grammar forbids dashes).
String docSpecsIdTransform(String id) =>
    id.replaceAll(RegExp(r'[^a-zA-Z0-9_]+'), '_');

/// A `pattern-check` / `pattern-check-id` rule: the regex [pattern] plus the
/// authored [errorMessage].
class DocSpecsPatternCheck {
  DocSpecsPatternCheck({required this.pattern, this.errorMessage});

  final String pattern;
  final String? errorMessage;

  bool matches(String value) => RegExp(pattern).hasMatch(value);
}

/// One subsection slot of a section-type: `min-count` (default 0) and
/// `max-count` (`null` = infinite).
class DocSpecsSubsectionRule {
  DocSpecsSubsectionRule({required this.minCount, required this.maxCount});

  final int minCount;
  final int? maxCount;
}

/// One `section-types:` entry of a DocSpecs schema.
class DocSpecsSectionType {
  DocSpecsSectionType({
    required this.name,
    required this.prefix,
    this.patternCheckId,
    this.subsectionTypes = const {},
    this.format,
    this.textRequired = false,
    this.minTextLength,
    this.maxTextLength,
    this.description,
    this.validationPrompt,
  });

  final String name;

  /// The id prefix (in transformed grammar — see [docSpecsIdTransform]) a
  /// heading id must start with to resolve to this type.
  final String prefix;

  final DocSpecsPatternCheck? patternCheckId;

  /// Allowed child section-type names → cardinality.
  final Map<String, DocSpecsSubsectionRule> subsectionTypes;

  /// A form-type name (`*-form`) or a raw content format (`code`, `mermaid`).
  final String? format;

  final bool textRequired;
  final int? minTextLength;
  final int? maxTextLength;
  final String? description;

  /// Carried as data (DR1 §6) — not interpreted by this validator.
  final String? validationPrompt;
}

/// One field of a `form-types:` entry.
class DocSpecsFormField {
  DocSpecsFormField({
    required this.name,
    this.required = false,
    this.description,
    this.patternCheck,
  });

  final String name;
  final bool required;
  final String? description;
  final DocSpecsPatternCheck? patternCheck;
}

/// One `form-types:` entry: an ordered field list.
class DocSpecsFormType {
  DocSpecsFormType({required this.name, required this.fields});

  final String name;
  final List<DocSpecsFormField> fields;
}

/// One `document: sections:` slot: the backing section-type and whether the
/// slot is optional.
class DocSpecsDocumentSection {
  DocSpecsDocumentSection({required this.sectionType, required this.optional});

  final String sectionType;
  final bool optional;
}

/// A loaded `*.docspecs-schema.yaml` (the DR3 output format): the
/// `title-format`, the ordered [sectionTypes] (file order — descending prefix
/// length in generated schemas, so first-startsWith-match is longest-prefix
/// resolution), the [formTypes], and the [documentSections]. Schema features
/// outside the DR1 §6 scope are ignored on load and named in [warnings].
class DocSpecsSchema {
  DocSpecsSchema._();

  String? titleFormat;

  /// Section types in file order; resolution takes the **first** type whose
  /// [DocSpecsSectionType.prefix] is a prefix of the transformed id.
  final List<DocSpecsSectionType> sectionTypes = [];
  final Map<String, DocSpecsSectionType> sectionTypesByName = {};
  final Map<String, DocSpecsFormType> formTypes = {};
  final Map<String, DocSpecsDocumentSection> documentSections = {};

  /// Every schema feature encountered but not interpreted, named (DR1 §7:
  /// nothing is silently dropped).
  final List<String> warnings = [];

  /// The root section id demanded by [titleFormat], when derivable.
  String? get rootSectionId {
    final tf = titleFormat;
    if (tf == null) return null;
    return RegExp(r'<!--\[([^\]]+)\]-->').firstMatch(tf)?.group(1);
  }

  static const _sectionTypeKeys = {
    'prefix',
    'pattern-check-id',
    'subsection-types',
    'format',
    'text-required',
    'min-text-length',
    'max-text-length',
    'description',
    'validation-prompt',
  };

  /// Loads a schema from its YAML [text]. Malformed YAML throws; unsupported
  /// features are collected into [DocSpecsSchema.warnings] instead.
  static DocSpecsSchema fromYamlText(String text) {
    final schema = DocSpecsSchema._();
    final rootNode = loadYaml(text);
    if (rootNode is! Map) {
      throw FormatException('docspecs schema must be a YAML map');
    }
    final root = rootNode;
    for (final key in root.keys) {
      final k = '$key';
      switch (k) {
        case 'title-format':
          schema.titleFormat = '${root[key]}';
        case 'section-types':
          _loadSectionTypes(schema, root[key]);
        case 'form-types':
          _loadFormTypes(schema, root[key]);
        case 'document':
          _loadDocument(schema, root[key]);
        case 'schema' || 'version' || 'name' || 'description':
          break; // informational headers — accepted, no semantics here.
        default:
          schema.warnings.add('unsupported top-level schema key "$k" ignored');
      }
    }
    return schema;
  }

  static DocSpecsPatternCheck? _patternCheck(Object? node) {
    if (node == null) return null;
    if (node is Map) {
      return DocSpecsPatternCheck(
        pattern: '${node['pattern']}',
        errorMessage:
            node['error-message'] == null ? null : '${node['error-message']}',
      );
    }
    return DocSpecsPatternCheck(pattern: '$node');
  }

  static void _loadSectionTypes(DocSpecsSchema schema, Object? node) {
    if (node is! Map) return;
    for (final entry in node.entries) {
      final name = '${entry.key}';
      final st = entry.value;
      if (st is! Map) continue;
      final subs = <String, DocSpecsSubsectionRule>{};
      final subsNode = st['subsection-types'];
      if (subsNode is Map) {
        for (final s in subsNode.entries) {
          final rule = s.value;
          final min = rule is Map ? rule['min-count'] : null;
          final max = rule is Map ? rule['max-count'] : null;
          subs['${s.key}'] = DocSpecsSubsectionRule(
            minCount: min is int ? min : 0,
            maxCount: max is int ? max : null, // 'infinite' or absent → null
          );
        }
      }
      for (final key in st.keys) {
        if (!_sectionTypeKeys.contains('$key')) {
          schema.warnings.add(
              'unsupported key "$key" on section-type "$name" ignored');
        }
      }
      final type = DocSpecsSectionType(
        name: name,
        prefix: '${st['prefix'] ?? docSpecsIdTransform(name.toUpperCase())}',
        patternCheckId: _patternCheck(st['pattern-check-id']),
        subsectionTypes: subs,
        format: st['format'] == null ? null : '${st['format']}',
        textRequired: st['text-required'] == true,
        minTextLength:
            st['min-text-length'] is int ? st['min-text-length'] as int : null,
        maxTextLength:
            st['max-text-length'] is int ? st['max-text-length'] as int : null,
        description: st['description'] == null ? null : '${st['description']}',
        validationPrompt: st['validation-prompt'] == null
            ? null
            : '${st['validation-prompt']}',
      );
      schema.sectionTypes.add(type);
      schema.sectionTypesByName[name] = type;
    }
  }

  static void _loadFormTypes(DocSpecsSchema schema, Object? node) {
    if (node is! Map) return;
    for (final entry in node.entries) {
      final name = '${entry.key}';
      final ft = entry.value;
      if (ft is! Map) continue;
      for (final key in ft.keys) {
        if ('$key' != 'fields') {
          schema.warnings
              .add('unsupported key "$key" on form-type "$name" ignored');
        }
      }
      final fields = <DocSpecsFormField>[];
      final fieldsNode = ft['fields'];
      if (fieldsNode is List) {
        for (final f in fieldsNode) {
          if (f is! Map) continue;
          fields.add(DocSpecsFormField(
            name: '${f['fieldname']}',
            required: f['required'] == true,
            description:
                f['description'] == null ? null : '${f['description']}',
            patternCheck: _patternCheck(f['pattern-check']),
          ));
        }
      }
      schema.formTypes[name] = DocSpecsFormType(name: name, fields: fields);
    }
  }

  static void _loadDocument(DocSpecsSchema schema, Object? node) {
    if (node is! Map) return;
    for (final key in node.keys) {
      final k = '$key';
      if (k == 'sections') {
        final sections = node[key];
        if (sections is! Map) continue;
        for (final s in sections.entries) {
          final v = s.value;
          schema.documentSections['${s.key}'] = DocSpecsDocumentSection(
            sectionType:
                v is Map ? '${v['section-type'] ?? s.key}' : '${s.key}',
            optional: v is Map && v['optional'] == true,
          );
        }
      } else if (k != 'name' && k != 'description') {
        schema.warnings.add('unsupported document key "$k" ignored');
      }
    }
  }

  /// Resolves a heading [id] to its section-type: the first type (file order)
  /// whose [DocSpecsSectionType.prefix] prefixes the transformed id.
  DocSpecsSectionType? resolveSectionType(String id) {
    final transformed = docSpecsIdTransform(id);
    for (final t in sectionTypes) {
      if (transformed.startsWith(t.prefix)) return t;
    }
    return null;
  }
}

