/// Emits the DocSpecs schema accessor (SOM §10.3) for the TypeScript and
/// JavaScript facades: `<package>_schemas.ts` / `<package>_schemas.js`.
///
/// The same accessor the Dart facade has had (`SomDartSchemasEmitter`):
/// `somDocSpecsSchema(id)` returns the runtime's `DocSpecsSchema`, parsed on
/// first use and cached; `somDocSpecsSchemaIds` lists the ids;
/// `somDocSpecsSchemaYaml` holds the exact YAML of the shipped
/// `schemas/<id>/…docspecs-schema.yaml` files. Each schema is **embedded**
/// rather than read from the `schemas/` tree, so a bundler (a VS Code
/// extension packs with one) needs no file copy and no package-relative path
/// survives into the bundle. It is a separate module, not part of the facade,
/// so a consumer that never validates does not load ~2 MB of YAML.
library;

import 'dart:convert';

import 'package:tom_doc_specs/tom_doc_specs.dart';

import 'docspecs_schema_generator.dart';

/// Which of the two script planes the module is written for.
enum SomScriptPlane {
  /// A `.ts` module importing the runtime by its bare package name.
  typescript,

  /// A CommonJS `.js` module locating the runtime through the package's
  /// `tomSom.runtimePath`, exactly as the JavaScript facade does.
  javascript,
}

/// Generates the schema accessor module for one script plane.
class SomScriptSchemasEmitter {
  /// The generated schemas, keyed as [DocSpecsSchemaGenerator.generateAll]
  /// returns them.
  final Map<String, DocSpecSchema> schemas;

  /// The facade package's name (`tom_som_typescript_v0`, …).
  final String packageName;

  /// The plane the module is written for.
  final SomScriptPlane plane;

  /// The version label written into the generated header.
  final String versionLabel;

  /// All four are fixed for one generation run.
  SomScriptSchemasEmitter(
    this.schemas, {
    required this.packageName,
    required this.plane,
    this.versionLabel = 'v0',
  });

  /// The module's file name, beside the facade.
  String get fileName =>
      '${packageName}_schemas.${plane == SomScriptPlane.typescript ? 'ts' : 'js'}';

  /// Schema id → YAML text, sorted by id: the same text
  /// [DocSpecsSchemaGenerator.writeSchemaTree] writes to `schemas/`.
  Map<String, String> get texts {
    final byId = {for (final s in schemas.values) s.id: s};
    final ids = byId.keys.toList()..sort();
    return {
      for (final id in ids) id: DocSpecsSchemaGenerator.toYamlString(byId[id]!),
    };
  }

  /// The module source.
  String generateModule() {
    final ts = plane == SomScriptPlane.typescript;
    final b = StringBuffer();
    b.writeln(
      '// GENERATED by tom_specs_clitool SomScriptSchemasEmitter '
      '($versionLabel) — do not edit by hand.',
    );
    if (!ts) b.writeln("'use strict';");
    b.writeln('//');
    b.writeln('// The DocSpecs schema accessor (SOM §10.3). Each schema is');
    b.writeln(
      '// embedded rather than read from the shipped `schemas/` tree, so',
    );
    b.writeln(
      '// a bundled consumer needs no file copy. A separate module from',
    );
    b.writeln('// the facade: importing the facade does not load the schemas.');
    b.writeln();
    if (ts) {
      b.writeln("import { DocSpecsSchema } from 'tom_som_typescript_runtime';");
    } else {
      b.writeln("const _path = require('path');");
      b.writeln("const _manifest = require('./package.json');");
      b.writeln(
        'const { DocSpecsSchema } = '
        'require(_path.resolve(__dirname, _manifest.tomSom.runtimePath));',
      );
    }
    b.writeln();
    b.writeln('/**');
    b.writeln(' * The embedded schemas, as the exact YAML of the shipped');
    b.writeln(' * `schemas/<id>/<id>.<major>.0.docspecs-schema.yaml` files.');
    b.writeln(' */');
    b.writeln(
      ts
          ? 'export const somDocSpecsSchemaYaml: Readonly<Record<string, string>> = {'
          : 'const somDocSpecsSchemaYaml = Object.freeze({',
    );
    for (final e in texts.entries) {
      b.writeln('  ${jsonEncode(e.key)}: ${jsonEncode(e.value)},');
    }
    b.writeln(ts ? '};' : '});');
    b.writeln();
    b.writeln('/** Every schema id this package carries, sorted. */');
    b.writeln(
      ts
          ? 'export const somDocSpecsSchemaIds: readonly string[] = '
                'Object.keys(somDocSpecsSchemaYaml);'
          : 'const somDocSpecsSchemaIds = '
                'Object.freeze(Object.keys(somDocSpecsSchemaYaml));',
    );
    b.writeln();
    b.writeln(
      ts
          ? 'const _cache = new Map<string, DocSpecsSchema>();'
          : 'const _cache = new Map();',
    );
    b.writeln();
    b.writeln('/**');
    b.writeln(' * The generated DocSpecs schema for the document root `id` —');
    b.writeln(' * the `@Document` name lower-cased and hyphenated');
    b.writeln(' * (`solution-blueprint`, …). Parsed on first use and cached.');
    b.writeln(
      ' * Throws naming every known id when `id` is not one of them: a',
    );
    b.writeln(' * typo must not read as an empty schema, which would validate');
    b.writeln(' * every document clean.');
    b.writeln(' */');
    b.writeln(
      ts
          ? 'export function somDocSpecsSchema(id: string): DocSpecsSchema {'
          : 'function somDocSpecsSchema(id) {',
    );
    b.writeln('  const cached = _cache.get(id);');
    b.writeln('  if (cached !== undefined) return cached;');
    b.writeln(
      '  if (!Object.prototype.hasOwnProperty.call(somDocSpecsSchemaYaml, id)) {',
    );
    b.writeln('    throw new Error(');
    b.writeln(
      r"      `unknown schema id '${id}'; known ids are ${somDocSpecsSchemaIds.join(', ')}`,",
    );
    b.writeln('    );');
    b.writeln('  }');
    b.writeln(
      '  const schema = DocSpecsSchema.fromYamlText(somDocSpecsSchemaYaml[id]);',
    );
    b.writeln('  _cache.set(id, schema);');
    b.writeln('  return schema;');
    b.writeln('}');
    if (!ts) {
      b.writeln();
      b.writeln('module.exports = {');
      b.writeln('  somDocSpecsSchema,');
      b.writeln('  somDocSpecsSchemaIds,');
      b.writeln('  somDocSpecsSchemaYaml,');
      b.writeln('};');
    }
    return b.toString();
  }
}
